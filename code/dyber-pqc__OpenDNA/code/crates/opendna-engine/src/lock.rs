//! Pinning an engine, the way `models.lock` pins a head.
//!
//! An engine that changed under a project is the same problem as a head that
//! changed under it: the numbers move and nothing says why. A lockfile is the
//! answer in both cases — write down what was validated, and fail later if
//! what is installed is not that.
//!
//! The file is plain text in a fixed order because it goes into a methods
//! section, a ticket and a diff, and has to be readable in all three.
//!
//! Only engines that were found are written. An absent engine is not pinned
//! to its absence: a lockfile saying "vina was not installed" would start
//! failing the day somebody installs it, which is the opposite of useful.

use crate::{Engine, EngineError, Requirement};
use std::fmt::Write as _;

/// Why a check failed.
#[derive(Debug, thiserror::Error)]
pub enum LockError {
    /// The installed engines are not the pinned ones.
    #[error("the installed engines are not the ones pinned in this lockfile:\n{differences}")]
    Mismatch {
        /// Line-by-line, what was expected against what is here.
        differences: String,
    },
}

/// Render a lockfile for what was discovered.
#[must_use]
pub fn lockfile(found: &[(&'static Requirement, Result<Engine, EngineError>)]) -> String {
    let mut out = String::new();
    out.push_str("# OpenDNA engines.lock\n");
    out.push_str("# Generated by `opendna engines --lock`. Commit this beside the analysis\n");
    out.push_str("# it produced; `opendna engines --check engines.lock` fails if the\n");
    out.push_str("# installed engines are not these.\n");
    out.push_str("#\n");
    out.push_str("# The digest covers the file invoked. For an entry point -- a script, a\n");
    out.push_str("# launcher, an interpreter -- that is not the whole of the software, and\n");
    out.push_str("# the version string carries the rest of the identity.\n");

    // Sorted by name so the file is stable across runs and diffs cleanly.
    let mut lines: Vec<String> = found
        .iter()
        .filter_map(|(requirement, outcome)| {
            let engine = outcome.as_ref().ok()?;
            Some(format!(
                "engine {} version = {} sha256 = {} identification = {}",
                requirement.name,
                engine.version,
                engine.sha256,
                match engine.identification {
                    crate::Identification::Executable => "executable",
                    crate::Identification::EntryPoint => "entry-point",
                }
            ))
        })
        .collect();
    lines.sort();
    for line in lines {
        let _ = writeln!(out, "{line}");
    }
    out
}

/// Compare a lockfile against what is installed.
///
/// Differing is an error rather than a warning, for the same reason it is for
/// the heads: the point of pinning is that a run against the wrong software
/// stops, instead of producing numbers nobody can place.
///
/// # Errors
/// [`LockError::Mismatch`] naming every line that differs, in both directions,
/// so the reader can see what changed rather than only that something did.
pub fn check(
    pinned: &str,
    found: &[(&'static Requirement, Result<Engine, EngineError>)],
) -> Result<(), LockError> {
    let meaningful = |text: &str| -> Vec<String> {
        text.lines()
            .map(str::trim)
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .map(str::to_owned)
            .collect()
    };
    let want = meaningful(pinned);
    let have = meaningful(&lockfile(found));
    if want == have {
        return Ok(());
    }

    let mut differences = String::new();
    for line in &want {
        if !have.contains(line) {
            let _ = writeln!(differences, "  pinned but not installed: {line}");
        }
    }
    for line in &have {
        if !want.contains(line) {
            let _ = writeln!(differences, "  installed but not pinned: {line}");
        }
    }
    Err(LockError::Mismatch { differences: differences.trim_end().to_string() })
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use crate::{Identification, Requirement};
    use std::path::PathBuf;

    static VINA: Requirement = Requirement {
        name: "vina",
        binaries: &["vina"],
        version_args: &["--version"],
        override_var: "OPENDNA_VINA",
        purpose: "ligand docking",
        identification: Identification::Executable,
    };

    static ESMFOLD: Requirement = Requirement {
        name: "esmfold",
        binaries: &["esmfold"],
        version_args: &["--version"],
        override_var: "OPENDNA_ESMFOLD",
        purpose: "structure prediction",
        identification: Identification::EntryPoint,
    };

    fn engine(name: &'static str, version: &str, sha: &str, id: Identification) -> Engine {
        Engine {
            name,
            path: PathBuf::from(format!("/usr/bin/{name}")),
            version: version.to_string(),
            sha256: sha.to_string(),
            identification: id,
        }
    }

    fn found(
        entries: Vec<(&'static Requirement, Result<Engine, EngineError>)>,
    ) -> Vec<(&'static Requirement, Result<Engine, EngineError>)> {
        entries
    }

    #[test]
    fn a_lockfile_round_trips_against_itself() {
        let entries = found(vec![(
            &VINA,
            Ok(engine("vina", "AutoDock Vina v1.2.5", &"ab".repeat(32), Identification::Executable)),
        )]);
        let text = lockfile(&entries);
        assert!(text.contains("engine vina version = AutoDock Vina v1.2.5"), "{text}");
        check(&text, &entries).unwrap();
    }

    #[test]
    fn a_changed_version_fails_the_check_and_shows_both() {
        let pinned = lockfile(&found(vec![(
            &VINA,
            Ok(engine("vina", "AutoDock Vina v1.2.5", &"ab".repeat(32), Identification::Executable)),
        )]));
        let now = found(vec![(
            &VINA,
            Ok(engine("vina", "AutoDock Vina v1.2.6", &"cd".repeat(32), Identification::Executable)),
        )]);
        let error = check(&pinned, &now).unwrap_err().to_string();
        assert!(error.contains("v1.2.5"), "the pinned version should be shown: {error}");
        assert!(error.contains("v1.2.6"), "the installed version should be shown: {error}");
    }

    /// An engine appearing where none was pinned is a change too. Somebody
    /// who pinned a run without vina and now has vina is not running what
    /// they pinned.
    #[test]
    fn an_engine_that_appeared_also_fails_the_check() {
        let pinned = lockfile(&found(vec![]));
        let now = found(vec![(
            &VINA,
            Ok(engine("vina", "AutoDock Vina v1.2.5", &"ab".repeat(32), Identification::Executable)),
        )]);
        let error = check(&pinned, &now).unwrap_err().to_string();
        assert!(error.contains("installed but not pinned"), "{error}");
    }

    /// An engine that is not installed is simply absent from the file, rather
    /// than pinned to its absence, which would fail the day it arrives.
    #[test]
    fn a_missing_engine_is_not_written_down() {
        let text = lockfile(&found(vec![(
            &VINA,
            Err(EngineError::NotFound { name: "vina", looked_for: "vina".into(), hint: String::new() }),
        )]));
        assert!(!text.contains("engine vina"), "{text}");
        // And an empty lockfile still checks against an empty install.
        check(&text, &found(vec![])).unwrap();
    }

    #[test]
    fn the_file_is_ordered_so_it_diffs_cleanly() {
        let text = lockfile(&found(vec![
            (&VINA, Ok(engine("vina", "v1", &"ab".repeat(32), Identification::Executable))),
            (&ESMFOLD, Ok(engine("esmfold", "v2", &"cd".repeat(32), Identification::EntryPoint))),
        ]));
        let esmfold = text.find("engine esmfold").unwrap();
        let vina = text.find("engine vina").unwrap();
        assert!(esmfold < vina, "entries should be sorted by name:\n{text}");
    }

    /// The distinction the crate makes a point of has to survive into the
    /// file, or a reader cannot tell a strong digest from a weak one.
    #[test]
    fn the_file_records_how_much_the_digest_identifies() {
        let text = lockfile(&found(vec![(
            &ESMFOLD,
            Ok(engine("esmfold", "v2", &"cd".repeat(32), Identification::EntryPoint)),
        )]));
        assert!(text.contains("identification = entry-point"), "{text}");
    }
}
