//! What is installed, and whether it is what it claims to be.
//!
//! A lab has to be able to answer three questions before it runs anything:
//! which models are here, are the files intact, and are they the same models
//! the last run used. None of that is answerable from a directory listing, so
//! this reads each head's metadata, verifies the weights against the hash it
//! records, and can write the result as a lockfile to compare against later.
//!
//! The lockfile is deliberately plain text in a fixed order: it goes into a
//! methods section, a ticket, or a diff, and it has to be readable there.

use anyhow::{bail, Context, Result};
use opendna_ml::esm2::ModelSize;
use opendna_ml::heads::{read_metadata, HeadFiles, HeadMetadata, Integrity};
use std::fmt::Write as _;
use std::path::Path;

/// Every task the application knows about, in the order they are reported.
pub const TASKS: [&str; 4] = ["stability", "solubility", "disorder", "burial"];

/// One head as found on disk.
pub struct Installed {
    /// Task name.
    pub task: &'static str,
    /// Metadata, when the head is present and readable.
    pub metadata: Option<HeadMetadata>,
    /// Why the head is unusable, when it is.
    pub problem: Option<String>,
    /// Result of checking the weights against the recorded hash.
    pub integrity: Integrity,
}

impl Installed {
    /// Whether this head can be used for a prediction.
    pub fn ready(&self) -> bool {
        self.metadata.is_some() && self.problem.is_none() && self.integrity.usable()
    }

    /// One line for a human: what it is, and whether it verified.
    pub fn describe(&self) -> String {
        let Some(m) = &self.metadata else {
            return self.problem.clone().unwrap_or_else(|| "not installed".into());
        };
        let build = m.build.as_deref().unwrap_or("unknown-build");
        match &self.integrity {
            Integrity::Verified => format!("{} ({build})  verified", m.version),
            Integrity::Unrecorded => {
                format!("{} ({build})  NOT VERIFIABLE: metadata records no weights hash", m.version)
            }
            Integrity::Mismatch { expected, actual } => format!(
                "{} ({build})  CORRUPT: weights hash {} but metadata records {}",
                m.version,
                &actual[..16],
                &expected[..16]
            ),
        }
    }
}

/// Inspect every head in `dir`.
///
/// Never fails on a missing or broken head: a report whose job is to say what
/// is wrong cannot stop at the first thing that is.
pub fn scan(dir: &Path, embedder: ModelSize) -> Vec<Installed> {
    TASKS
        .iter()
        .map(|task| {
            let files = HeadFiles::in_dir(dir, task);
            if !files.exist() {
                return Installed {
                    task,
                    metadata: None,
                    problem: Some("not installed".into()),
                    integrity: Integrity::Unrecorded,
                };
            }
            match read_metadata(&files, task, embedder) {
                Ok(metadata) => {
                    let integrity = files.verify(&metadata).unwrap_or(Integrity::Unrecorded);
                    Installed { task, metadata: Some(metadata), problem: None, integrity }
                }
                Err(e) => Installed {
                    task,
                    metadata: None,
                    problem: Some(e.to_string()),
                    integrity: Integrity::Unrecorded,
                },
            }
        })
        .collect()
}

/// Render the lockfile for a scan.
///
/// Only heads that are present appear: a lockfile records what was used, and
/// pinning the absence of something is not a useful claim.
pub fn lockfile(installed: &[Installed], embedder: ModelSize) -> String {
    let mut out = String::new();
    out.push_str("# OpenDNA models.lock\n");
    out.push_str("# Generated by `opendna models lock`. Commit this beside the analysis\n");
    out.push_str("# it produced; `opendna models --check models.lock` fails if the\n");
    out.push_str("# installed heads are not these.\n");
    let _ = writeln!(out, "embedding_model = {}", embedder.repo());
    for head in installed {
        let Some(m) = &head.metadata else { continue };
        let _ = writeln!(
            out,
            "head {} version = {} build = {} sha256 = {}",
            head.task,
            m.version,
            m.build.as_deref().unwrap_or("unknown"),
            m.weights_sha256.as_deref().unwrap_or("unrecorded")
        );
    }
    out
}

/// Compare an existing lockfile against what is installed.
///
/// # Errors
/// If the lockfile cannot be read, or if what is installed differs from it.
/// Differing is an error rather than a warning: the point of pinning is that
/// a run against the wrong models stops instead of producing numbers nobody
/// can place.
pub fn check(path: &Path, installed: &[Installed], embedder: ModelSize) -> Result<()> {
    let want = std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    let have = lockfile(installed, embedder);
    let strip = |text: &str| -> Vec<String> {
        text.lines()
            .map(str::trim)
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .map(str::to_owned)
            .collect()
    };
    let (want, have) = (strip(&want), strip(&have));
    if want == have {
        return Ok(());
    }
    let mut report = String::from("the installed models are not the ones in the lockfile\n");
    for line in &want {
        if !have.contains(line) {
            let _ = writeln!(report, "  expected: {line}");
        }
    }
    for line in &have {
        if !want.contains(line) {
            let _ = writeln!(report, "  found:    {line}");
        }
    }
    bail!("{}", report.trim_end());
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    fn head(task: &'static str, version: &str, build: &str, sha: Option<&str>) -> Installed {
        Installed {
            task,
            metadata: Some(HeadMetadata {
                task: task.into(),
                embedding_model: "facebook/esm2_t30_150M_UR50D".into(),
                embedding_dim: 640,
                version: version.into(),
                build: Some(build.into()),
                weights_sha256: sha.map(str::to_owned),
                with_burial: false,
                calibration: None,
                abstention: None,
                intervals: None,
            }),
            problem: None,
            integrity: if sha.is_some() { Integrity::Verified } else { Integrity::Unrecorded },
        }
    }

    #[test]
    fn a_lockfile_names_the_version_build_and_hash_of_each_head() {
        let text = lockfile(&[head("disorder", "1.0.0", "abc123", Some("ff00"))], ModelSize::Large150M);
        assert!(text.contains("head disorder version = 1.0.0 build = abc123 sha256 = ff00"), "{text}");
        assert!(text.contains("embedding_model = facebook/esm2_t30_150M_UR50D"), "{text}");
    }

    #[test]
    fn a_head_that_is_absent_is_not_pinned() {
        let absent = Installed {
            task: "burial",
            metadata: None,
            problem: Some("not installed".into()),
            integrity: Integrity::Unrecorded,
        };
        let text = lockfile(&[absent], ModelSize::Large150M);
        assert!(!text.contains("head burial"), "{text}");
    }

    /// The whole point of the lockfile: a different model has to stop the run.
    #[test]
    fn a_changed_version_fails_the_check() {
        let dir = std::env::temp_dir().join(format!("opendna-lock-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("models.lock");
        std::fs::write(
            &path,
            lockfile(&[head("disorder", "1.0.0", "abc", Some("ff"))], ModelSize::Large150M),
        )
        .unwrap();

        let same = check(&path, &[head("disorder", "1.0.0", "abc", Some("ff"))], ModelSize::Large150M);
        assert!(same.is_ok(), "an identical install must pass: {same:?}");

        let bumped = check(&path, &[head("disorder", "1.1.0", "abc", Some("ff"))], ModelSize::Large150M);
        let err = bumped.unwrap_err().to_string();
        assert!(err.contains("expected:") && err.contains("found:"), "{err}");
        assert!(err.contains("1.0.0") && err.contains("1.1.0"), "{err}");

        let retrained = check(&path, &[head("disorder", "1.0.0", "zzz", Some("ff"))], ModelSize::Large150M);
        assert!(retrained.is_err(), "a retrain that kept the version must still be caught");
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn comments_and_blank_lines_do_not_affect_the_comparison() {
        let dir = std::env::temp_dir().join(format!("opendna-lock2-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("models.lock");
        std::fs::write(&path, "# a note someone added\n\nembedding_model = facebook/esm2_t30_150M_UR50D\nhead disorder version = 1.0.0 build = abc sha256 = ff\n").unwrap();
        assert!(check(&path, &[head("disorder", "1.0.0", "abc", Some("ff"))], ModelSize::Large150M).is_ok());
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn an_unverifiable_head_is_still_usable_but_a_corrupt_one_is_not() {
        let unrecorded = head("disorder", "1.0.0", "abc", None);
        assert!(unrecorded.ready());
        assert!(unrecorded.describe().contains("NOT VERIFIABLE"), "{}", unrecorded.describe());

        let mut corrupt = head("disorder", "1.0.0", "abc", Some("aa"));
        corrupt.integrity = Integrity::Mismatch { expected: "a".repeat(64), actual: "b".repeat(64) };
        assert!(!corrupt.ready());
        assert!(corrupt.describe().contains("CORRUPT"), "{}", corrupt.describe());
    }
}
