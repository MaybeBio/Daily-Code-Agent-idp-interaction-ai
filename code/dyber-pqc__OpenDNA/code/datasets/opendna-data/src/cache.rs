//! Download cache with a SHA-256 lockfile.
//!
//! Every upstream file is stored at `<cache>/<source id>/<file name>`. The
//! lockfile (`sources.lock`, committed to the repository) records the URL,
//! size and SHA-256 of each file the datasets were built from.
//!
//! Rules:
//! * A cached file whose hash matches the lockfile is reused without network access.
//! * A file with no lockfile entry is downloaded (or hashed, if already cached)
//!   and its hash is recorded.
//! * A hash mismatch is an error. Upstream data changing silently is exactly the
//!   failure the lockfile exists to catch; pass `--update-lock` to accept it.
//! * Downloads are written to a `.part` file and renamed only after the hash
//!   has been computed, so an interrupted run never leaves a truncated file at
//!   the final path.

use std::collections::BTreeMap;
use std::fs::{self, File};
use std::io::{BufReader, BufWriter, Read, Write};
use std::path::{Path, PathBuf};
use std::time::Duration;

use anyhow::{bail, Context, Result};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::sources::Source;

pub const LOCK_VERSION: u32 = 1;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockEntry {
    pub url: String,
    pub file: String,
    pub bytes: u64,
    pub sha256: String,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lockfile {
    pub version: u32,
    /// Keyed by source id; a BTreeMap keeps the serialised file sorted and diff-friendly.
    #[serde(default)]
    pub sources: BTreeMap<String, LockEntry>,
}

impl Lockfile {
    pub fn load(path: &Path) -> Result<Self> {
        if !path.exists() {
            return Ok(Self { version: LOCK_VERSION, sources: BTreeMap::new() });
        }
        let text =
            fs::read_to_string(path).with_context(|| format!("reading lockfile {}", path.display()))?;
        Self::parse(&text).with_context(|| format!("parsing lockfile {}", path.display()))
    }

    pub fn parse(text: &str) -> Result<Self> {
        let lock: Lockfile = toml::from_str(text)?;
        if lock.version != LOCK_VERSION {
            bail!("unsupported lockfile version {} (expected {LOCK_VERSION})", lock.version);
        }
        Ok(lock)
    }

    pub fn to_toml(&self) -> Result<String> {
        let body = toml::to_string_pretty(self)?;
        Ok(format!(
            "# Generated by opendna-data. Records the exact upstream files the datasets\n\
             # were built from. Do not edit by hand; use `opendna-data --update-lock`.\n\n{body}"
        ))
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        let tmp = path.with_extension("lock.tmp");
        fs::write(&tmp, self.to_toml()?)?;
        fs::rename(&tmp, path).with_context(|| format!("writing lockfile {}", path.display()))
    }
}

/// Outcome of checking a candidate file against the lockfile.
#[derive(Debug, PartialEq, Eq)]
pub enum LockCheck {
    Matches,
    New,
    Mismatch { expected: String, actual: String },
}

pub fn check_against_lock(lock: &Lockfile, src: &Source, sha256: &str) -> LockCheck {
    match lock.sources.get(src.id) {
        None => LockCheck::New,
        Some(e) if e.sha256 == sha256 && e.url == src.url => LockCheck::Matches,
        Some(e) if e.url != src.url => LockCheck::New,
        Some(e) => LockCheck::Mismatch { expected: e.sha256.clone(), actual: sha256.to_owned() },
    }
}

pub struct Cache {
    root: PathBuf,
    lock_path: PathBuf,
    lock: Lockfile,
    update_lock: bool,
    offline: bool,
}

impl Cache {
    pub fn open(root: &Path, lock_path: &Path, update_lock: bool, offline: bool) -> Result<Self> {
        fs::create_dir_all(root).with_context(|| format!("creating cache dir {}", root.display()))?;
        Ok(Self {
            root: root.to_owned(),
            lock_path: lock_path.to_owned(),
            lock: Lockfile::load(lock_path)?,
            update_lock,
            offline,
        })
    }

    pub fn lock(&self) -> &Lockfile {
        &self.lock
    }

    pub fn path_for(&self, src: &Source) -> PathBuf {
        self.root.join(src.id).join(src.file_name)
    }

    /// Returns the local path of `src`, downloading it if needed, and verifies
    /// it against the lockfile.
    pub fn fetch(&mut self, src: &Source) -> Result<PathBuf> {
        let path = self.path_for(src);
        if path.exists() {
            let (sha, bytes) = hash_file(&path)?;
            self.reconcile(src, &path, sha, bytes)?;
            return Ok(path);
        }
        if self.offline {
            bail!("{} is not cached at {} and --offline was given", src.id, path.display());
        }
        fs::create_dir_all(path.parent().expect("cache path has a parent"))?;
        let part = path.with_file_name(format!("{}.part", src.file_name));
        eprintln!("downloading {} -> {}", src.url, path.display());
        let (sha, bytes) = download(src.url, &part)?;
        if let LockCheck::Mismatch { expected, actual } = check_against_lock(&self.lock, src, &sha) {
            if !self.update_lock {
                bail!(
                    "upstream file for {} changed: lockfile has sha256 {expected}, download has {actual}.\n\
                     The partial download was kept at {}. Re-run with --update-lock to accept the new data.",
                    src.id,
                    part.display()
                );
            }
        }
        fs::rename(&part, &path)?;
        self.reconcile(src, &path, sha, bytes)?;
        Ok(path)
    }

    /// Fetch one file of a bulk collection, returning its path and SHA-256.
    ///
    /// The lockfile pins the handful of catalogue files a dataset is built
    /// from — a Zenodo archive, a DisProt release — and that is the right
    /// granularity for them: a change upstream should stop the build. It is
    /// the wrong granularity for the thousands of individual coordinate files
    /// the burial dataset reads, which would turn `sources.lock` into a
    /// register of PDB entries and bury the sources that actually define the
    /// build.
    ///
    /// So these are pinned in the dataset's own manifest instead: the caller
    /// collects the digests this returns and writes them beside the data, so
    /// a build is still reproducible file by file. What stops silent drift is
    /// that the *catalogue* which chose these entries — the CATH release —
    /// is lockfile-pinned, so the set cannot change without the build
    /// stopping.
    ///
    /// # Errors
    /// If the download fails, or the file is absent and `--offline` was given.
    pub fn fetch_bulk(&mut self, group: &str, name: &str, url: &str) -> Result<(PathBuf, String)> {
        let path = self.root.join(group).join(name);
        if path.exists() {
            let (sha, _) = hash_file(&path)?;
            return Ok((path, sha));
        }
        if self.offline {
            bail!("{name} is not cached at {} and --offline was given", path.display());
        }
        fs::create_dir_all(path.parent().expect("cache path has a parent"))?;
        let part = path.with_file_name(format!("{name}.part"));
        let (sha, _) = download(url, &part)?;
        fs::rename(&part, &path)?;
        Ok((path, sha))
    }

    /// Whether the cache may reach the network.
    pub fn is_offline(&self) -> bool {
        self.offline
    }

    fn reconcile(&mut self, src: &Source, path: &Path, sha: String, bytes: u64) -> Result<()> {
        match check_against_lock(&self.lock, src, &sha) {
            LockCheck::Matches => Ok(()),
            LockCheck::Mismatch { expected, actual } if !self.update_lock => bail!(
                "cached file {} has sha256 {actual} but the lockfile records {expected}.\n\
                 Delete the file to re-download, or pass --update-lock to accept it.",
                path.display()
            ),
            _ => {
                self.lock.sources.insert(
                    src.id.to_owned(),
                    LockEntry { url: src.url.to_owned(), file: src.file_name.to_owned(), bytes, sha256: sha },
                );
                self.lock.save(&self.lock_path)?;
                eprintln!("recorded {} in {}", src.id, self.lock_path.display());
                Ok(())
            }
        }
    }
}

/// Streams a file through SHA-256. Returns (hex digest, byte count).
pub fn hash_file(path: &Path) -> Result<(String, u64)> {
    let f = File::open(path).with_context(|| format!("opening {}", path.display()))?;
    hash_reader(BufReader::with_capacity(1 << 20, f))
}

pub fn hash_reader(mut r: impl Read) -> Result<(String, u64)> {
    let mut h = Sha256::new();
    let mut buf = vec![0u8; 1 << 20];
    let mut n = 0u64;
    loop {
        let k = r.read(&mut buf)?;
        if k == 0 {
            break;
        }
        h.update(&buf[..k]);
        n += k as u64;
    }
    Ok((hex::encode(h.finalize()), n))
}

const DOWNLOAD_ATTEMPTS: u32 = 4;

/// Downloads with bounded retries. Each attempt restarts from scratch (the
/// `.part` file is truncated), so a partial body from a failed attempt can
/// never be mixed into the result.
fn download(url: &str, dest: &Path) -> Result<(String, u64)> {
    let mut attempt = 1;
    loop {
        match download_once(url, dest) {
            Ok(r) => return Ok(r),
            Err(e) if attempt < DOWNLOAD_ATTEMPTS => {
                let wait = Duration::from_secs(10 * u64::from(attempt));
                eprintln!("attempt {attempt}/{DOWNLOAD_ATTEMPTS} failed: {e:#}; retrying in {wait:?}");
                std::thread::sleep(wait);
                attempt += 1;
            }
            Err(e) => return Err(e.context(format!("giving up after {DOWNLOAD_ATTEMPTS} attempts"))),
        }
    }
}

fn download_once(url: &str, dest: &Path) -> Result<(String, u64)> {
    let client = reqwest::blocking::Client::builder()
        .user_agent(concat!("opendna-data/", env!("CARGO_PKG_VERSION")))
        .connect_timeout(Duration::from_secs(60))
        .timeout(None)
        .build()?;
    let mut resp = client.get(url).send().with_context(|| format!("GET {url}"))?;
    if !resp.status().is_success() {
        bail!("GET {url} returned HTTP {}", resp.status());
    }
    let mut out = BufWriter::new(File::create(dest)?);
    let mut h = Sha256::new();
    let mut buf = vec![0u8; 1 << 20];
    let mut n = 0u64;
    loop {
        let k = resp.read(&mut buf)?;
        if k == 0 {
            break;
        }
        h.update(&buf[..k]);
        out.write_all(&buf[..k])?;
        n += k as u64;
    }
    out.flush()?;
    if n == 0 {
        bail!("GET {url} returned an empty body");
    }
    Ok((hex::encode(h.finalize()), n))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sources::{Source, SourceLicense};

    const SRC: Source = Source {
        id: "fixture",
        url: "https://example.invalid/data.txt",
        file_name: "data.txt",
        license: SourceLicense::Cc0,
        description: "test",
    };

    #[test]
    fn lockfile_roundtrip_is_sorted_and_stable() {
        let mut lock = Lockfile { version: LOCK_VERSION, sources: BTreeMap::new() };
        for id in ["zeta", "alpha"] {
            lock.sources.insert(
                id.into(),
                LockEntry {
                    url: format!("https://x/{id}"),
                    file: format!("{id}.bin"),
                    bytes: 3,
                    sha256: "00".into(),
                },
            );
        }
        let text = lock.to_toml().unwrap();
        assert!(text.find("alpha").unwrap() < text.find("zeta").unwrap());
        assert_eq!(Lockfile::parse(&text).unwrap(), lock);
        assert!(Lockfile::parse("version = 99\n").is_err());
    }

    #[test]
    fn lock_check_states() {
        let mut lock = Lockfile::default();
        assert_eq!(check_against_lock(&lock, &SRC, "aa"), LockCheck::New);
        lock.sources.insert(
            SRC.id.into(),
            LockEntry { url: SRC.url.into(), file: SRC.file_name.into(), bytes: 1, sha256: "aa".into() },
        );
        assert_eq!(check_against_lock(&lock, &SRC, "aa"), LockCheck::Matches);
        assert!(matches!(check_against_lock(&lock, &SRC, "bb"), LockCheck::Mismatch { .. }));
    }

    #[test]
    fn cached_file_is_hashed_recorded_and_then_verified() {
        let dir = tempfile::tempdir().unwrap();
        let cache_root = dir.path().join("cache");
        let lock_path = dir.path().join("sources.lock");
        fs::create_dir_all(cache_root.join("fixture")).unwrap();
        fs::write(cache_root.join("fixture/data.txt"), b"abc").unwrap();

        // Offline: never touches the network because the file is already cached.
        let mut cache = Cache::open(&cache_root, &lock_path, false, true).unwrap();
        cache.fetch(&SRC).unwrap();
        let lock = Lockfile::load(&lock_path).unwrap();
        assert_eq!(
            lock.sources["fixture"].sha256,
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert_eq!(lock.sources["fixture"].bytes, 3);

        // Corrupting the cached file must be detected.
        fs::write(cache_root.join("fixture/data.txt"), b"abd").unwrap();
        let mut cache = Cache::open(&cache_root, &lock_path, false, true).unwrap();
        assert!(cache.fetch(&SRC).is_err());
        // ... unless the caller explicitly accepts the change.
        let mut cache = Cache::open(&cache_root, &lock_path, true, true).unwrap();
        cache.fetch(&SRC).unwrap();
    }

    #[test]
    fn offline_missing_file_is_an_error() {
        let dir = tempfile::tempdir().unwrap();
        let mut cache = Cache::open(&dir.path().join("c"), &dir.path().join("l"), false, true).unwrap();
        let err = cache.fetch(&SRC).unwrap_err().to_string();
        assert!(err.contains("--offline"), "{err}");
    }
}
