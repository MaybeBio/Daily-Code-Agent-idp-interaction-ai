"""Write src/zpoly/forcefield/data/gaff2_so4.yaml from AmberTools' gaff2.dat.

    python devtools/extract_gaff2_so4.py /path/to/amber/dat/leap/parm/gaff2.dat

Keeps the GAFF2 terms that the sulfate end groups (C-O-SO3-) of OPLS-AA builds can need
(rqm/forcefield/builtin_charges.md): bonds and angles with os or s6, and dihedrals, all made of the
GAFF2 types the OPLS bonded types map to. Values are stored in GROMACS units.
"""

import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from zpoly.forcefield._amber import read_amber_parameters  # noqa: E402

TYPES = {"c3", "hc", "c", "ca", "o", "os", "n", "s6", "X"}
SULFATE = {"os", "s6"}


def main(path: str) -> None:
    p = read_amber_parameters(path)
    title = Path(path).read_text(encoding="ascii", errors="replace").splitlines()[0].strip()

    def ok(key, need_sulfate=True):
        return set(key) <= TYPES and (not need_sulfate or set(key) & SULFATE)

    data = {
        "version": 1,
        "source": title,
        "bonds": {"-".join(k): [round(b0, 6), round(kb, 3)] for k, (b0, kb) in sorted(p.bondtypes.items()) if ok(k)},
        "angles": {"-".join(k): [round(t, 4), round(kt, 4)] for k, (t, kt) in sorted(p.angletypes.items()) if ok(k)},
        "dihedrals": {"-".join(k): [[round(ph, 3), round(kd, 6), int(n)] for ph, kd, n in terms]
                      for k, terms in sorted(p.dihedraltypes.items()) if ok(k, need_sulfate=False)},
    }
    out = Path(__file__).resolve().parents[1] / "src/zpoly/forcefield/data/gaff2_so4.yaml"
    out.write_text("# GAFF2 terms for sulfate end groups in OPLS-AA builds (GROMACS units: nm, kJ/mol, deg).\n"
                   "# Generated by devtools/extract_gaff2_so4.py; do not edit by hand.\n"
                   "# Dihedrals: [phase, k, multiplicity] terms of k (1 + cos(n phi - phase)).\n"
                   + yaml.safe_dump(data, sort_keys=False, width=120, default_flow_style=None), encoding="utf-8")
    print(f"{out}: {len(data['bonds'])} bonds, {len(data['angles'])} angles, {len(data['dihedrals'])} dihedrals")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
