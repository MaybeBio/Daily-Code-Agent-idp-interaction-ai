"""Render docs/zwitterion_catalog.md from the built-in zwitterion library.

The YAML file src/zpoly/zwitterions/data/zwitterion_library.yaml is the single source of
truth. Usage:

    python devtools/build_zwitterion_catalog.py > docs/zwitterion_catalog.md
"""

# rq-a3c277ca

from __future__ import annotations

import sys

from zpoly.zwitterions import BlockCategory, default_library

SLOT = {
    BlockCategory.POLYMERIZABLE: "Polymerizable",
    BlockCategory.LINKER: "Linker",
    BlockCategory.CATION: "Cation",
    BlockCategory.SPACER: "Spacer",
    BlockCategory.ANION: "Anion",
}
STATUS = {"common": "Common", "specialty": "Specialty", "combinatorial": "Combinatorial*",
          "computed": "Computed only"}


def display(smiles: str) -> str:
    return smiles.replace("[*:1]", "[*]").replace("[*:2]", "[*]")


def charge_text(q: int) -> str:
    return "0 (+1/−1)" if q == 0 else f"{q:+d}".replace("-", "−")


def render() -> str:
    lib = default_library()
    out: list[str] = []
    w = out.append
    w("# Zwitterionic Monomer Building-Block Catalog\n")
    w("<!-- Generated by devtools/build_zwitterion_catalog.py from "
      "src/zpoly/zwitterions/data/zwitterion_library.yaml. Do not edit by hand. -->\n")
    w("This catalog splits zwitterionic monomers into interchangeable **building blocks** and lists "
      "the entries of the built-in library (`zpoly.zwitterions.default_library()`). "
      "Every entry was validated with RDKit when this page was generated: it parses, each zwitterion has "
      "net charge 0 with at least one + and one − centre, each comonomer is neutral or carries a "
      "counterion, and every monomer has a recognised "
      "polymerizable group. Entries defined by blocks are assembled from those blocks.\n")
    w("## How a zwitterionic monomer is decomposed\n")
    w("Using DMAPS (SBMA) as the example:\n")
    w("```")
    w("CH2=C(CH3)-C(=O)O-   -CH2CH2-   -N+(CH3)2-   -CH2CH2CH2-   -SO3-")
    w("  polymerizable        linker      cation        spacer        anion")
    w("   (methacrylate)                  (+1)       (CH2 bridge, n)   (-1)")
    w("```\n")
    w("- **Polymerizable group**: the C=C is what joins the polymer chain. In the polymer it becomes "
      "the backbone repeat unit -CH2-C(R)- (`Zwitterion.repeat_unit_smiles()`).")
    w("- **Linker**: connects the polymerizable group to the first charged group. Linear (CH2)n "
      "linkers use the spacer blocks `C1`–`C4` (or the `C<n>` shorthand).")
    w("- **Cation / anion**: the charged pair. The usual order is backbone → cation → anion "
      "(sulfo- and carboxybetaines). Phosphorylcholines (MPC) have the **inverted** order backbone → anion → cation.")
    w("- **Spacer** (the *CH2 bridge*): the carbon chain between the two charges. Its length *n* can be "
      "tuned, and `compose()` accepts any `C<n>`.\n")
    w("In the SMILES, `[*]` marks an attachment point. For a two-point fragment the first `[*]` "
      "faces the backbone and the second faces the chain end.\n")

    sections = [
        (BlockCategory.POLYMERIZABLE, "1. Polymerizable groups"),
        (BlockCategory.LINKER, "2. Linkers (non-alkylene)"),
        (BlockCategory.CATION, "3. Cationic groups"),
        (BlockCategory.SPACER, "4. Spacers and alkylene linkers"),
        (BlockCategory.ANION, "5. Anionic groups"),
    ]
    for category, title in sections:
        w(f"## {title}\n")
        blocks = lib.blocks(category)
        if not blocks:
            w("No blocks in this category yet. Alkylene linkers are the spacer blocks.\n")
            continue
        w("| Key | Name | SMILES fragment | SMARTS | Charge | Notes |")
        w("|---|---|---|---|---|---|")
        for b in blocks:
            smarts = f"`{b.smarts}`" if b.smarts else "—"
            charged = category in (BlockCategory.CATION, BlockCategory.ANION)
            charge = charge_text(b.formal_charge) if charged else "0"
            w(f"| {b.key} | {b.name} | `{display(b.smiles)}` | {smarts} | {charge} | {b.notes} |")
        w("")

    w("## 6. Zwitterionic monomers\n")
    w("Status: **Common** = widely used or commercially available; **Specialty** = reported in the "
      "literature, less common; **Combinatorial\\*** = valid combination of blocks, shown as an "
      "example (check literature/availability); **Computed only** = studied in simulation, not "
      "synthesized. **FF** lists force fields with curated parameters.\n")
    monomers = lib.entries(polymerizable=True)
    families: list[str] = []
    for z in monomers:
        if z.family not in families:
            families.append(z.family)
    for fam in sorted(families):
        w(f"### {fam}\n")
        w("| Name | Aliases | Full name | Blocks | SMILES | Formula | MW | Status | FF |")
        w("|---|---|---|---|---|---|---|---|---|")
        for z in monomers:
            if z.family != fam:
                continue
            blocks = " → ".join(z.blocks) if z.blocks else "—"
            ff = ", ".join(f.value for f in z.parameters) or "—"
            w(f"| {z.name} | {', '.join(z.aliases) or '—'} | {z.full_name} | {blocks} | `{z.smiles}` | "
              f"{z.formula} | {z.molecular_weight:.2f} | {STATUS[z.status]} | {ff} |")
        w("")

    w("## 7. Zwitterionic liquids and small-molecule zwitterions\n")
    w("These do not polymerize. They are used as solvents, additives or osmolytes, and are relevant to LLPS.\n")
    w("| Name | Full name | SMILES | Formula | MW | Status |")
    w("|---|---|---|---|---|---|")
    for z in lib.entries(polymerizable=False):
        w(f"| {z.name} | {z.full_name} | `{z.smiles}` | {z.formula} | {z.molecular_weight:.2f} | {STATUS[z.status]} |")

    w("\n## 8. Initiators and end groups\n")
    w("Initiator fragments cap the chain head (bonded to the first unit's CH2, where the radical adds) "
      "and/or the tail (bonded to the last unit's substituted carbon). Choose with "
      "`build_chain(units, initiator=..., ends='both' | 'head' | 'tail' | 'none')`. For example, KPS gives "
      "`…-O-SO3⁻` at each capped end, so a chain capped at both ends has net charge −2. Define your own "
      "initiator in a YAML file (`initiators:`) or with `custom_initiator()`.\n")
    w("| Name | Aliases | Full name | Head group | Tail group | Charge (head/tail) | Counterion | FF |")
    w("|---|---|---|---|---|---|---|---|")
    for i in lib.initiators():
        head = f"`{display(i.head_smiles)}`" if i.head_smiles else "—"
        tail = f"`{display(i.tail_smiles)}`" if i.tail_smiles else "—"
        ff = ", ".join(f.value for f in i.parameters) or "—"
        charges = " / ".join(charge_text(q) if q else "0" for q in (i.head_charge, i.tail_charge))
        w(f"| {i.name} | {', '.join(i.aliases) or '—'} | {i.full_name} | {head} | {tail} | "
          f"{charges} | {i.counterion or '—'} | {ff} |")

    w("\n## 9. Interaction strengths from Schneider et al.\n")
    w("Source: *Rational design of zwitterionic polymers with tunable phase separation propensity*, "
      "Schneider, Ye, Carrara, Capasso Palmiero, Salvalaglio, Arosio, SI Table S1. F_min is the "
      "homotypic monomer–monomer interaction free energy from umbrella sampling; **a higher F_min "
      "means stronger self-attraction and a higher phase-separation propensity**.\n")
    w("| Name | F_min [kBT] | Status | Cation block(s) | Anion block(s) |")
    w("|---|---|---|---|---|")
    with_fmin = [z for z in lib if "fmin_kbt" in z.properties]
    for z in sorted(with_fmin, key=lambda z: (-float(z.properties["fmin_kbt"]), z.name)):
        err = z.properties.get("fmin_kbt_error")
        val = f"{z.properties['fmin_kbt']}" + (f" ± {err}" if err is not None else "")
        w(f"| {z.name} | {val} | {STATUS[z.status]} | {', '.join(z.cation_classes) or '—'} | "
          f"{', '.join(z.anion_classes) or '—'} |")
    w("\nNotes:\n")
    w("- **ZB4 inconsistency in the SI.** The synthesis text (MEMA + ethylene sulfate) gives an ethylene "
      "spacer (`ZB4`). The Table S1 drawing shows a propylene spacer (`ZB4-C3`, which carries the F_min value).")
    w("- In the paper, `SB` is DMAPS and `CB` is the n = 1 carboxybetaine `CBMA-1`.")
    w("- Where more than one cation block is listed, the generic ring SMARTS also matches the larger ring "
      "system (for example, isoquinolinium contains a pyridinium ring).\n")

    w("## 10. Not yet covered\n")
    w("- **Polyampholytes**: separate cationic monomers (e.g. METAC, VBTAC, DADMAC) and anionic monomers "
      "(e.g. AMPS, SSS, acrylic acid) copolymerized in one chain.")
    w("- **Amino-acid zwitterions** (−NH3+ … −COO−) and pH-switchable tertiary-amine betaines.")
    w("- **Non-vinyl backbones**: ring-opening (norbornene, cyclic esters), polypeptoids, step-growth.")
    w("- **Multi-charge zwitterions** (e.g. +2/−2, or DABCO-based dications with two sulfonates).")
    w("- Force-field parameters. The charges here are formal charges only. Curated OPLS-AA parameters "
      "exist only where the FF column says so.")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render())
