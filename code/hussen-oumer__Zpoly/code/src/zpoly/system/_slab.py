def slab_system(monomer, n: int | None = None, *, chains: int, box_nm=None, slab_nm: float | None = None,
                density: float | None = None, aspect: float = 3.0, initiator: str | None = None,
                ends: str | None = None, spacer: int | None = None,
                alkyl: int | None = None, dft=None, dft_parts: str = "whole", cap: str = "CH3",
                builtin_charges: bool = True, solvent: str = "tip3p",
                charge_scale: float = 1.0, ff: str = "gaff2", packer: str = "packmol",
                salt: str | None = "NaCl", salt_molar: float = 0.15,
                t_equil: float = 300.0, temperatures=(280, 300, 320, 340, 360), times_ns: dict | None = None,
                seed: int = 0, solvent_ff: str | os.PathLike | None = None, out: str | os.PathLike = "slab",
                library: Library | None = None) -> Path:
    """Build an LLPS slab system and its protocol."""
    if salt not in SALTS:
        raise ValueError(f"salt must be one of NaCl, KCl or None, got {salt!r}")
    if salt is not None and salt_molar <= 0:
        raise ValueError("salt_molar must be > 0 (or use salt=None)")
    if not isinstance(chains, int) or chains < 1:
        raise ValueError(f"chains must be an integer >= 1, got {chains!r}")
    if not temperatures:
        raise ValueError("Give at least one production temperature.")
    if density is not None:  # rq-7c268316: the box follows from the density
        if box_nm is not None or slab_nm is not None:
            raise ValueError("Give either DENSITY or BOX and SLAB, not both")
        if isinstance(density, bool) or not isinstance(density, (int, float)) or density <= 0:
            raise ValueError(f"density must be > 0 g/cm3, got {density!r}")
        if not aspect >= 3.0:
            raise ValueError(f"aspect (Lz / Lx) must be at least 3, got {aspect!r}")
    elif box_nm is None or slab_nm is None:
        raise TypeError("slab_system needs density, or box_nm and slab_nm")
    else:
        lx, _, lz, thick = check_slab_box(box_nm, slab_nm)
    if packer not in ("packmol", "builtin", "emc"):
        raise ValueError(f"packer must be 'packmol', 'builtin' or 'emc', got {packer!r}")
    times = dict(DEFAULT_TIMES)
    unknown = set(times_ns or {}) - set(times)
    if unknown:
        raise ValueError(f"Unknown times_ns key(s) {', '.join(sorted(unknown))}; use {', '.join(times)}")
    times.update(times_ns or {})
    if solvent == "tip4p2005" and abs(charge_scale - 0.85) > 1e-9:
        raise ValueError("SOLVENT = tip4p2005 uses the Madrid-2019 ions (charges +-0.85 e): "
                         "set CHARGE_SCALE = 0.85 so the system is neutral")
    lib = library if library is not None else default_library()
    units, aliases = resolve_units(monomer, n, spacer, alkyl, lib)

    structures = build_chains(units, 1 if packer == "emc" else chains, initiator, ends, seed, lib, cap)
    structures = structures * chains if packer == "emc" else structures
    first = structures[0]
    if isinstance(dft, dict):
        dft = dft_charges_from_values(dft, first.units, first.initiator, aliases)
    topology = parametrize(first, ff, name=NAME, dft_charges=dft, dft_parts=dft_parts, charge_scale=charge_scale,
                           builtin_charges=builtin_charges)

    ion, n_ions = counterions_for(first, chains)
    salt_ions = SALTS[salt]
    needed = list(dict.fromkeys([*([ion] if ion else []), *(salt_ions or ()), "SOL"]))
    parts = solvent_parts(topology, needed, solvent_ff, water_file="tip3p.itp", solvent=solvent)

    poly_mass = chain_mass(topology) * chains + (parts.masses[ion] * n_ions if ion else 0.0)
    if density is not None:
        lx = (poly_mass * AMU_G / density * 1e24) ** (1 / 3)  # Å
        lz, thick = aspect * lx, lx
        cube = (poly_mass * AMU_G / min(density, PACK_DENSITY) * 1e24) ** (1 / 3)
    box = (lx, lx, lz)
    slab_density = density_g_cm3(poly_mass, lx * lx * thick)
    region = (lz / 2 - thick / 2, lz / 2 + thick / 2) if density is None else None
    pieces = []
    emc_piece = chain_piece(first, emc=True) if packer == "emc" else None
    for s in structures:
        p = dataclasses.replace(emc_piece) if emc_piece is not None else chain_piece(s)
        p.region = region
        pieces.append(p)
    ion_pieces = []
    if ion:
        for _ in range(n_ions):
            p = ion_piece(parts.molecules[ion])
            p.region = region
            ion_pieces.append(p)
    counts: list[tuple[str, int]] = [(ion, n_ions)] if ion else []
    extra_molecules: list = [parts.molecules[ion]] * n_ions if ion else []
    if density is not None:  # pack a dry cube; GROMACS compresses it and adds the water later
        placed = pack(pieces + ion_pieces, (cube, cube, cube), packer, seed)
        start_gro = "packed.gro"
    elif packer == "packmol":
        v_box_nm3 = lx * lx * lz / 1000.0
        v_poly_nm3 = poly_mass * AMU_G / DRY_POLYMER_DENSITY * 1e21
        n_water = max(0, round(WATER_PER_NM3 * (v_box_nm3 - v_poly_nm3)))
        n_salt = round(salt_molar * n_water / 55.5) if salt_ions else 0
        sol = parts.molecules["SOL"]
        water = [_water_piece(sol.atom_names)] * n_water
        salt_pieces, salt_mols = [], []
        if salt_ions:
            for name in salt_ions:
                salt_pieces += [ion_piece(parts.molecules[name])] * n_salt
                salt_mols += [parts.molecules[name]] * n_salt
        placed = pack(pieces + ion_pieces + water + salt_pieces, box, "packmol", seed)
        extra_molecules += [sol] * n_water + salt_mols
        counts.append(("SOL", n_water))
        if salt_ions:  # separate lines, in system.gro order (a molecule name may repeat, e.g. K for KCl)
            counts += [(name, n_salt) for name in salt_ions]
        start_gro = "system.gro"
    else:
        try:
            placed = pack(pieces + ion_pieces, box, packer, seed)
        except SystemBuildError as exc:
            raise SystemBuildError(f"{exc} For a slab: make SLAB thicker, BOX wider, CHAINS fewer, "
                                   "or use PACKER = packmol.") from None
        start_gro = "packed.gro"
    q = total_charge(topology, chains, parts, _summed(counts))
    if abs(q) > 1e-3:
        raise SystemBuildError(f"The system's total charge is {q:+.4f}, not 0.")

    folder = Path(out)
    folder.mkdir(parents=True, exist_ok=True)
    write_forcefield(folder, topology, parts)
    title = f"{chains} x {'-'.join(dict.fromkeys(z.name for z in units))} ({len(units)} units) LLPS slab"
    write_system_top(folder, title, chains, counts, True, True, charge_scale)
    extra = list(zip(extra_molecules, placed[chains:], strict=True))
    natoms = write_gro(folder / start_gro, title, first, placed[:chains], extra,
                       box if density is None else (cube, cube, cube))
    n_poly_atoms = first.mol.GetNumAtoms() * chains
    (folder / "index.ndx").write_text(_index(n_poly_atoms), encoding="ascii")

    prelude: list[str] = []
    solute = "packed.gro"
    if density is not None:
        # velocities from a short NVT: no deform-init-flow (any GROMACS)
        compress = Step("00_compress", "nvt", t_equil, times["compress"],
                        deform_nm_ps=(lx - cube) / 10 / (times["compress"] * 1000))
        for step in (Step("00_em", "em"), Step("00_heat", "nvt", t_equil, 0.01, generate_velocities=True), compress):
            (folder / f"{step.name}.mdp").write_text(mdp_text(step), encoding="ascii")
        nm = [f"{v / 10:.5f}" for v in (lx, lx, lz)]
        prelude = ["echo '== densify the dry cube and build the slab box'",
                   "$GMX grompp -f 00_em.mdp -c packed.gro -p system.top -o 00_em.tpr -maxwarn $MAXWARN",
                   "$GMX mdrun -deffnm 00_em -nt $NT",
                   "$GMX grompp -f 00_heat.mdp -c 00_em.gro -p system.top -o 00_heat.tpr -maxwarn $MAXWARN",
                   "$GMX mdrun -deffnm 00_heat -nt $NT",
                   "$GMX grompp -f 00_compress.mdp -c 00_heat.gro -t 00_heat.cpt -p system.top -o 00_compress.tpr "
                   "-maxwarn $MAXWARN",
                   "$GMX mdrun -deffnm 00_compress -nt $NT",
                   "echo 0 | $GMX trjconv -s 00_compress.tpr -f 00_compress.gro -o 00_whole.gro -pbc mol",
                   f"$GMX editconf -f 00_whole.gro -o slab_box.gro -box {' '.join(nm)} "
                   f"-center {float(nm[0]) / 2:.5f} {float(nm[1]) / 2:.5f} {float(nm[2]) / 2:.5f}", ""]
        solute = "slab_box.gro"
    if packer != "packmol" or density is not None:
        prelude += ["echo '== solvate and add salt'",
                    f"$GMX solvate -cp {solute} -cs {'tip4p.gro' if solvent == 'tip4p2005' else 'spc216.gro'} "
                    "-o solvated.gro -p system.top"]
        if salt_ions:
            pname, nname = salt_ions
            prelude += ["$GMX grompp -f 01_em.mdp -c solvated.gro -p system.top -o genion.tpr -maxwarn 1",
                        f"echo SOL | $GMX genion -s genion.tpr -o system.gro -p system.top -pname {pname} "
                        f"-nname {nname} -conc {salt_molar:g} -neutral"]
        else:
            prelude += ["cp solvated.gro system.gro"]
        prelude.append("")

    steps = [Step("01_em", "em"),
             Step("02_nvt", "nvt", t_equil, times["nvt"], generate_velocities=True),
             Step("03_npt_z", "npt", t_equil, times["npt_z"], 1.0, semiisotropic_z=True)]
    prods = [Step(_pname(t), "nvt", float(t), times["production"], generate_velocities=True) for t in temperatures]
    for step in steps + prods:
        (folder / f"{step.name}.mdp").write_text(mdp_text(step), encoding="ascii")
    (folder / "run.sh").write_text(_run_script(steps, prods, prelude), encoding="ascii")
    (folder / "run_production.sh").write_text(_production_script(steps[-1].name), encoding="ascii")
    total_ns = sum(s.time_ns for s in steps + prods)
    (folder / "run_slurm.sh").write_text(slurm_script(folder.name or "slab", total_ns), encoding="ascii")
    for script in ("run.sh", "run_production.sh", "run_slurm.sh"):
        (folder / script).chmod(0o755)
    protocol = {
        "kind": "slab", "title": title, "force_field": topology.force_field, "charge_scale": charge_scale,
        "solvent": solvent,
        "chains": chains,
        "units": [z.name for z in units], "initiator": first.chain.initiator, "counterion": ion,
        "counterions": n_ions, "salt": salt, "salt_molar": salt_molar if salt else 0.0, "packer": packer,
        "box_nm": [round(b / 10, 5) for b in box], "slab_thickness_nm": round(thick / 10, 4),
        "slab_density_g_cm3": round(slab_density, 4), "polymer_atoms": n_poly_atoms,
        "atoms_before_solvation": natoms if packer != "packmol" or density is not None else None,
        "atoms": natoms if packer == "packmol" and density is None else None,
        "density_g_cm3": density, "aspect": aspect if density is not None else None,
        "packing_cube_nm": round(cube / 10, 5) if density is not None else None,
        "t_equil": t_equil, "dft_blocks": list(topology.dft_blocks),
        "steps": [{"name": s.name, "kind": s.kind, "temperature": s.temperature, "time_ns": s.time_ns} for s in steps],
        "productions": [{"name": s.name, "temperature": s.temperature, "time_ns": s.time_ns} for s in prods],
        "total_ns": total_ns,
    }
    (folder / "protocol.yaml").write_text(yaml.safe_dump(protocol, sort_keys=False), encoding="utf-8")
    salt_txt = f"{salt} {salt_molar:g} M" if salt else "none"
    print(f"{folder}: {chains} chains + {n_ions} {ion or 'counterions'}, box {lx / 10:g} x {lx / 10:g} x "
          f"{lz / 10:g} nm, slab {thick / 10:g} nm (starting slab density {slab_density:.3f} g/cm3), "
          f"salt {salt_txt}, {len(prods)} temperatures. Run {folder / 'run.sh'}, then analyze_slab.")
    return folder


def _summed(counts):
    out: dict[str, int] = {}
    for name, c in counts:
        out[name] = out.get(name, 0) + c
    return out
