SALTS = {"NaCl": ("NA", "CL"), "KCl": ("K", "CL"), None: None}
DEFAULT_TIMES = {"nvt": 1.0, "npt_z": 5.0, "production": 200.0, "compress": 1.0}
PACK_DENSITY = 0.35  # g/cm3, density mode: the chains are packed at this density, then GROMACS compresses
WATER_PER_NM3 = 33.4
DRY_POLYMER_DENSITY = 1.3  # g/cm3, for the water count of the Packmol path
OH, HOH = 0.9572, math.radians(104.52)  # TIP3P geometry (Å, rad)


def _water_piece(names) -> Piece:
    xyz = [[0.0, 0.0, 0.0], [OH, 0.0, 0.0], [OH * math.cos(HOH), OH * math.sin(HOH), 0.0]]
    if len(names) == 4:  # TIP4P/2005: M on the bisector, 0.1546 A from O
        bisector = (np.array(xyz[1]) + np.array(xyz[2])) / 2
        xyz.append(list(bisector / np.linalg.norm(bisector) * 0.1546))
    return Piece(np.array(xyz), list(names))


def _pname(t: float) -> str:
    return f"prod_{int(t)}K" if float(t).is_integer() else f"prod_{t:g}K"


# rq-5fbd6a40
def check_slab_box(box_nm, slab_nm) -> tuple[float, float, float, float]:
    """Check the user's box and slab"""
    lx, ly, lz = box_angstrom(box_nm)
    if abs(lx - ly) > 1e-6:
        raise ValueError(f"The slab box needs Lx = Ly, got {lx / 10:g} and {ly / 10:g} nm")
    if lz < 3.0 * lx - 1e-6:
        raise ValueError(f"The slab box needs Lz >= 3 Lx ({3 * lx / 10:g} nm), got Lz = {lz / 10:g} nm")
    if isinstance(slab_nm, bool) or not isinstance(slab_nm, (int, float)) or not 0 < slab_nm * 10.0 <= lz + 1e-6:
        raise ValueError(f"slab_nm must be > 0 and at most Lz ({lz / 10:g} nm), got {slab_nm!r}")
    return lx, ly, lz, float(slab_nm) * 10.0


def _run_script(steps, productions, prelude) -> str:
    out = ["#!/usr/bin/env bash", "# LLPS slab protocol (generated by Zpoly).",
           "# Set GMX (default gmx) and NT (mdrun threads, default 0 = automatic) in the environment.",
           "set -euo pipefail", 'cd "$(dirname "$0")"', "GMX=${GMX:-gmx}", "NT=${NT:-0}",
           "MAXWARN=${MAXWARN:-0}", ""] + prelude
    prev = "system"
    for k, step in enumerate(steps):
        cpt = f" -t {prev}.cpt" if k > 0 and steps[k - 1].kind != "em" and not step.generate_velocities else ""
        out += [f"echo '== {step.name}'",
                f"$GMX grompp -f {step.name}.mdp -c {prev}.gro{cpt} -p system.top -o {step.name}.tpr -maxwarn $MAXWARN",
                f"$GMX mdrun -deffnm {step.name} -nt $NT", ""]
        prev = step.name
    for step in productions:
        out += [f"echo '== {step.name}'",
                f"$GMX grompp -f {step.name}.mdp -c {prev}.gro -p system.top -o {step.name}.tpr -maxwarn $MAXWARN",
                f"$GMX mdrun -deffnm {step.name} -nt $NT", ""]
    out.append("echo 'done'")
    return "\n".join(out) + "\n"


def _production_script(equilibrated: str) -> str:
    return ("#!/usr/bin/env bash\n# Run one production temperature after equilibration: run_production.sh 300\n"
            'set -euo pipefail\ncd "$(dirname "$0")"\nGMX=${GMX:-gmx}\nNT=${NT:-0}\nMAXWARN=${MAXWARN:-0}\n'
            'T=${1:?usage: run_production.sh TEMPERATURE_K}\n'
            f'$GMX grompp -f prod_${{T}}K.mdp -c {equilibrated}.gro -p system.top -o prod_${{T}}K.tpr '
            '-maxwarn $MAXWARN\n$GMX mdrun -deffnm prod_${T}K -nt $NT\n')


def _index(n_polymer_atoms: int) -> str:
    ids = [str(i) for i in range(1, n_polymer_atoms + 1)]
    lines = ["[ Polymer ]"] + [" ".join(ids[k:k + 15]) for k in range(0, len(ids), 15)]
    return "\n".join(lines) + "\n"


