"""GROMACS protocol files: .mdp per step, run.sh, run_slurm.sh."""

# rq-2d93d71c

from __future__ import annotations

from dataclasses import dataclass

DT = 0.002  # ps
COMMON = """cutoff-scheme        = Verlet
nstlist              = 20
pbc                  = xyz
coulombtype          = PME
rcoulomb             = 1.2
rvdw                 = 1.2
DispCorr             = EnerPres
"""


@dataclass(frozen=True)
class Step:
    name: str  # file stem, e.g. "02_nvt_hot" or "cool_300K"
    kind: str  # "em", "nvt", "npt"
    temperature: float | None = None
    time_ns: float = 0.0
    pressure_bar: float | None = None
    generate_velocities: bool = False
    semiisotropic_z: bool = False  # slab systems: pressure coupling along z only
    deform_nm_ps: float = 0.0  # box edge change per ps along x, y and z (negative: shrink), NVT only

    @property
    def nsteps(self) -> int:
        return int(round(self.time_ns * 1000 / DT))


def mdp_text(step: Step) -> str:
    if step.kind == "em":
        return ("; energy minimization (Zpoly)\nintegrator           = steep\nemtol                = 1000\n"
                "emstep               = 0.01\nnsteps               = 50000\n" + COMMON)
    lines = [f"; {step.name}: {step.kind.upper()} {step.temperature:g} K, {step.time_ns:g} ns (Zpoly)",
             "integrator           = md", f"dt                   = {DT}", f"nsteps               = {step.nsteps}",
             COMMON.rstrip("\n"),
             "constraints          = h-bonds", "constraint-algorithm = lincs",
             "tcoupl               = V-rescale", "tc-grps              = System", "tau-t                = 0.1",
             f"ref-t                = {step.temperature:g}",
             "nstcalcenergy        = 100", "nstenergy            = 1000", "nstlog               = 5000",
             "nstxout-compressed   = 5000"]
    if step.generate_velocities:
        lines += ["gen-vel              = yes", f"gen-temp             = {step.temperature:g}",
                  "gen-seed             = 1", "continuation         = no"]
    else:
        lines += ["gen-vel              = no", "continuation         = yes"]
    if step.kind == "npt":
        if step.semiisotropic_z:
            lines += ["pcoupl               = C-rescale", "pcoupltype           = semiisotropic",
                      "tau-p                = 2.0",
                      f"ref-p                = {step.pressure_bar:g} {step.pressure_bar:g}",
                      "compressibility      = 0 4.5e-5"]
        else:
            lines += ["pcoupl               = C-rescale", "pcoupltype           = isotropic",
                      "tau-p                = 2.0", f"ref-p                = {step.pressure_bar:g}",
                      "compressibility      = 4.5e-5"]
    else:
        lines += ["pcoupl               = no"]
    if step.deform_nm_ps:
        r = f"{step.deform_nm_ps:.8f}"
        lines += [f"deform               = {r} {r} {r} 0 0 0"]
    return "\n".join(lines) + "\n"


def run_script(steps: list[Step], start: str = "system") -> str:
    out = ["#!/usr/bin/env bash", "# Runs the protocol in order (generated by Zpoly).",
           "# Set GMX (default gmx) and NT (mdrun threads, default 0 = automatic) in the environment.",
           "set -euo pipefail", 'cd "$(dirname "$0")"', "GMX=${GMX:-gmx}", "NT=${NT:-0}",
           "MAXWARN=${MAXWARN:-0}", ""]
    prev = start
    for k, step in enumerate(steps):
        cpt = "" if k == 0 or step.generate_velocities or steps[k - 1].kind == "em" else f" -t {prev}.cpt"
        out += [f"echo '== {step.name}'",
                f"$GMX grompp -f {step.name}.mdp -c {prev}.gro{cpt} -p system.top -o {step.name}.tpr "
                f"-maxwarn $MAXWARN",
                f"$GMX mdrun -deffnm {step.name} -nt $NT", ""]
        prev = step.name
    out.append("echo 'done'")
    return "\n".join(out) + "\n"


def slurm_script(job: str, total_ns: float, ns_per_day: float = 50.0) -> str:
    hours = max(1, int(total_ns / ns_per_day * 24) + 1)
    return ("#!/usr/bin/env bash\n"
            f"#SBATCH --job-name={job}\n#SBATCH --nodes=1\n#SBATCH --ntasks=1\n#SBATCH --cpus-per-task=16\n"
            f"#SBATCH --time={hours:02d}:00:00\n"
            f"# --time assumes {ns_per_day:g} ns/day for {total_ns:g} ns in total; edit it for your machine.\n"
            "export NT=${SLURM_CPUS_PER_TASK:-0}\n"
            'bash "$(dirname "$0")/run.sh"\n')
