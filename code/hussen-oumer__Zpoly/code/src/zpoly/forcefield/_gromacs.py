def write_gromacs(topology: Topology, out_dir: str | os.PathLike, name: str | None = None,
                  padding: float = 10.0) -> Path:
    """Write <name>.pdb, <name>.top and <name>.ff/ into out_dir"""
    name = name or topology.name
    if topology.missing_parameters:
        from ._errors import MissingParameterError
        from ._params import parameter_template

        raise MissingParameterError(dict(topology.missing_parameters),
                                    parameter_template(topology.missing_parameters,
                                                       topology.parameters.dihedral_funct))
    files = {**forcefield_files(topology, name), f"{name}.top": _top(topology, name)}
    out = Path(out_dir)
    (out / f"{name}.ff").mkdir(parents=True, exist_ok=True)
    write_pdb(topology.structure, out / f"{name}.pdb", padding=padding)
    for rel, text in files.items():
        (out / rel).write_text(text, encoding="ascii")
    return out / f"{name}.top"


def forcefield_files(topology: Topology, name: str) -> dict[str, str]:
    """Rendered <name>.ff/ files (relative path -> text)."""
    return {
        f"{name}.ff/forcefield.itp": _forcefield_itp(topology, name),
        f"{name}.ff/forcefield.doc": f"{topology.force_field.upper()} for {name} (generated by Zpoly)\n",
        f"{name}.ff/ffnonbonded.itp": _ffnonbonded(topology),
        f"{name}.ff/ffbonded.itp": _ffbonded(topology),
        f"{name}.ff/{name}.rtp": _rtp(topology),
    }
