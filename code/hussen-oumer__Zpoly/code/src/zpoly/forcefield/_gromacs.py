_SAFE = re.compile(r"[^A-Za-z0-9_]")


def _molname(name: str) -> str:
    return _SAFE.sub("_", name) or "polymer"


def _forcefield_itp(top: Topology, name: str) -> str:
    nbfunc, comb, gen_pairs, fudge_lj, fudge_qq = top.parameters.defaults
    return (
        f"; {name}.ff: {top.force_field} parameters generated by Zpoly\n\n"
        "[ defaults ]\n"
        "; nbfunc  comb-rule  gen-pairs  fudgeLJ  fudgeQQ\n"
        f"  {nbfunc:<8d}{comb:<11d}{gen_pairs:<11s} {fudge_lj:<9g}{fudge_qq:g}\n\n"
        '#include "ffnonbonded.itp"\n'
        '#include "ffbonded.itp"\n'
    )


def _ffnonbonded(top: Topology) -> str:
    types = top.parameters.atomtypes
    with_bt = any(at.bonded_key != at.name for at in types.values())
    head = "; name      btype  at.num" if with_bt else "; name  at.num"
    lines = ["[ atomtypes ]", f"{head}        mass    charge ptype          sigma        epsilon"]
    for name in sorted(types):
        at = types[name]
        bt = f"{at.bonded_key:<7s} " if with_bt else ""
        lines.append(f"  {name:<10s} {bt}{at.atomic_number:6d}{at.mass:12.4f}{0.0:10.4f}     A"
                     f"{at.sigma:15.6e}{at.epsilon:15.6e}")
    return "\n".join(lines) + "\n"


def _ffbonded(top: Topology) -> str:
    p = top.parameters
    user = set(top.user_parameters)

    def mark(kind, key):
        return "   ; user" if (kind, key) in user else ""

    out = ["[ bondtypes ]", "; i     j      func        b0            kb"]
    for (a, b), (b0, kb) in sorted(p.bondtypes.items()):
        out.append(f"  {a:<6s} {b:<6s} {1:5d}{b0:14.6f}{kb:16.4f}{mark('bond', (a, b))}")
    out += ["", "[ angletypes ]", "; i     j     k      func       th0          cth"]
    for (a, b, c), (th, k) in sorted(p.angletypes.items()):
        out.append(f"  {a:<6s} {b:<6s} {c:<6s} {1:5d}{th:12.4f}{k:14.6f}{mark('angle', (a, b, c))}")
    if p.dihedral_funct == 3:
        out += ["", "[ dihedraltypes ]", "; i     j     k     l      func     C0          C1          C2"
                "          C3          C4          C5"]
        for (a, b, c, d), coeffs in sorted(p.dihedraltypes.items()):
            out.append(f"  {a:<6s} {b:<6s} {c:<6s} {d:<6s} {3:5d}" + "".join(f"{x:12.5f}" for x in coeffs)
                       + mark("dihedral", (a, b, c, d)))
    else:
        out += ["", "[ dihedraltypes ]", "; i     j     k     l      func       phase           kd   pn"]
        for (a, b, c, d), terms in sorted(p.dihedraltypes.items()):
            for phase, kd, pn in terms:
                out.append(f"  {a:<6s} {b:<6s} {c:<6s} {d:<6s} {9:5d}{phase:12.4f}{kd:14.6f}{pn:5d}"
                           + mark("dihedral", (a, b, c, d)))
    out += ["", "[ dihedraltypes ]", "; impropers", "; i     j     k     l      func       phase           kd   pn"]
    for (a, b, c, d), (phase, kd, pn) in sorted(p.impropertypes.items()):
        out.append(f"  {a:<6s} {b:<6s} {c:<6s} {d:<6s} {4:5d}{phase:12.4f}{kd:14.6f}{pn:5d}"
                   + mark("improper", (a, b, c, d)))
    return "\n".join(out) + "\n"


def _values(v) -> str:
    """Parameters written after the atoms of a bonded line"""
    return "  " + " ".join(f"{x:.6f}".rstrip("0").rstrip(".") for x in v) if v else ""


def _rtp_terms(top: Topology) -> dict[str, list]:
    """Residue name -> [(atom labels, values)]"""
    mol = top.structure.mol
    res = [a.GetIntProp("resnum") for a in mol.GetAtoms()]
    first = {}
    for a in mol.GetAtoms():
        first.setdefault(a.GetProp("res"), a.GetIntProp("resnum"))
    out: dict[str, list] = {}
    for term, values in top.explicit.items():
        owner = max(res[i] for i in term)
        if min(res[i] for i in term) < owner - 1:
            continue  # spans three residues: only in the .top
        name = mol.GetAtomWithIdx(term[0]).GetProp("res") if res[term[0]] == owner else next(
            mol.GetAtomWithIdx(i).GetProp("res") for i in term if res[i] == owner)
        if first[name] != owner:
            continue  # the residue's block is written from its first copy
        labels = tuple(("-" if res[i] < owner else "") + mol.GetAtomWithIdx(i).GetProp("name") for i in term)
        out.setdefault(name, []).append((labels, values))
    return out


def _rtp(top: Topology) -> str:
    bt = top.parameters.rtp_bondedtypes
    terms = _rtp_terms(top)
    out = [
        "[ bondedtypes ]",
        "; bonds  angles  dihedrals  impropers  all_dihedrals  nrexcl  HH14  RemoveDih",
        "  " + "".join(f"{v:<9d}" for v in bt).rstrip(),
    ]
    for block in top.blocks:
        out += ["", f"[ {block.name} ]", " [ atoms ]"]
        for k, (nm, t, q) in enumerate(zip(block.atom_names, block.atom_types, block.charges, strict=True), 1):
            out.append(f"  {nm:<6s} {t:<8s} {q:10.4f}{k:6d}")
        mine = {labels: v for labels, v in terms.get(block.name, ())}
        out.append(" [ bonds ]")
        out += [f"  {a:<7s} {b:<7s}" + _values(mine.get((a, b)) or mine.get((b, a))) for a, b in block.bonds]
        for size, section in ((3, "angles"), (4, "dihedrals")):
            lines = [f"  {' '.join(f'{x:<7s}' for x in labels)}" + _values(v) for labels, v in mine.items()
                     if len(labels) == size]
            if lines:
                out += [f" [ {section} ]"] + lines
        if block.impropers:
            out.append(" [ impropers ]")
            out += ["  " + "".join(f"{x:<7s} " for x in imp).rstrip() for imp in block.impropers]
    return "\n".join(out) + "\n"


def _top(top: Topology, name: str) -> str:
    mname = _molname(name)
    q = top.net_charge
    counter = top.structure.chain.counterion
    if q == 0:
        charge_note = "; net charge 0"
    elif counter:
        charge_note = f"; net charge {q:+d}: add {abs(q)} {counter}"
    else:
        charge_note = f"; net charge {q:+d}: add counterions to neutralize"
    if top.charge_scale != 1:
        charge_note += (f"\n; ionic groups: charges scaled by {top.charge_scale:g} (net charge "
                        f"{q * top.charge_scale:+.4g}); scale the counterions and salt by the same factor")
    out = [
        f"; {name}: {top.force_field} topology generated by Zpoly",
        charge_note,
        f'#include "{name}.ff/forcefield.itp"',
        "",
        moleculetype_text(top, mname).rstrip("\n"),
        "", "[ system ]", f"  {name}", "", "[ molecules ]", "; compound   nmols", f"  {mname:<16s} 1",
    ]
    return "\n".join(out) + "\n"


def moleculetype_text(top: Topology, mname: str) -> str:
    """The chain's [ moleculetype ] block."""
    mol = top.structure.mol
    out = [
        "[ moleculetype ]",
        "; name            nrexcl",
        f"  {mname:<16s} 3",
        "",
        "[ atoms ]",
        ";   nr  type     resnr  residue  atom    cgnr     charge       mass",
    ]
    total = 0.0
    for i, atom in enumerate(mol.GetAtoms()):
        t = top.atom_types[i]
        resnum = atom.GetIntProp("resnum")
        total += top.charges[i]
        out.append(f"  {i + 1:5d}  {t:<10s} {resnum:6d}  {atom.GetProp('res'):<8s} {atom.GetProp('name'):<6s} "
                   f"{resnum:6d}{top.charges[i]:11.4f}{top.parameters.atomtypes[t].mass:11.4f}"
                   f"   ; qtot {total:.4f}")
    out += ["", "[ bonds ]", ";   ai    aj funct"]
    ex = top.explicit
    out += [f"  {a + 1:5d} {b + 1:5d}     1" + _values(ex.get((a, b))) for a, b in top.bonds]
    out += ["", "[ pairs ]", ";   ai    aj funct"]
    out += [f"  {a + 1:5d} {b + 1:5d}     1" for a, b in top.pairs]
    out += ["", "[ angles ]", ";   ai    aj    ak funct"]
    out += [f"  {a + 1:5d} {b + 1:5d} {c + 1:5d}     1" + _values(ex.get((a, b, c))) for a, b, c in top.angles]
    out += ["", "[ dihedrals ]", "; propers", ";   ai    aj    ak    al funct"]
    funct = top.parameters.dihedral_funct
    out += [f"  {a + 1:5d} {b + 1:5d} {c + 1:5d} {d + 1:5d} {funct:5d}" + _values(ex.get((a, b, c, d)))
            for a, b, c, d in top.propers]
    if top.impropers:
        out += ["", "[ dihedrals ]", "; impropers", ";   ai    aj    ak    al funct"]
        out += [f"  {a + 1:5d} {b + 1:5d} {c + 1:5d} {d + 1:5d}     4" for a, b, c, d in top.impropers]
    return "\n".join(out) + "\n"


