"""
This is a small tool you can use to visulise domains predicted by InterPro
onto PAE plots generated by AlphaFold.
This can be useful for a quick sanity check to check that domain boundaries from the structural
and sequence-based predictions line up.
It also makes comparison and visualisation of many proteins more consistent and efficient.
Usage: python plot_af3_domains.py --json-dir AF3_output --tsv interpro_input
"""

import argparse
import glob
import hashlib
import json
import os
import re
import textwrap
import zlib
from dataclasses import dataclass, replace
import matplotlib.pyplot as plt
import numpy as np
from matplotlib import collections, lines, patches, ticker, transforms
plt.switch_backend("Agg")


OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "graphs")
MAX_EVALUE = 1e-3

# This is the priority order that annotation sources are chosen from
TIERS = [{"PFAM"}, {"SMART", "CDD"}, {"SUPERFAMILY", "CATH-GENE3D"},
         {"NCBIFAM", "PANTHER", "CATH-FUNFAM", "PIRSF", "SFLD"}]
TIER = {db: i for i, dbs in enumerate(TIERS) for db in dbs}

# Reduce if plots are too noisy
MAX_OVERLAP_AA, MAX_OVERLAP_FRAC = 10, 0.25 

# If there are are more than 16 domains, colours will start repeating, I suggest adding more
# Note, this is per domain, not per protein, so a multimer where several proteins contain a certain domain
# will share one colour for said domain
PALETTE = ["#d18f00", "#a0522d", "#cc5500", "#1f4e79", "#8e44ad", "#c71585", "#4b6584", "#b5651d",
           "#6a3d9a", "#d35400", "#2e86c1", "#922b21", "#5d6d7e", "#af7ac5", "#e67e22", "#17a2b8"]
PLDDT_BANDS = [(90, "#0053d6", "Very high (>90)"), (70, "#65cbf3", "Confident (70-90)"),
               (50, "#ffdb13", "Low (50-70)"), (0, "#ff7d45", "Very low (<50)")]
BOUNDARY, COIL, DISORDER = "#d7191c", "#52514e", "#9a9993"
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"

AA = dict(zip("ALA ARG ASN ASP CYS GLN GLU GLY HIS ILE LEU LYS MET PHE PRO SER THR TRP TYR VAL".split(),
              "ARNDCQEGHILKMFPSTWYV"))

plt.rcParams.update({
    "font.family": "DejaVu Sans", "font.size": 10, "axes.edgecolor": MUTED,
    "axes.labelcolor": INK, "xtick.color": MUTED, "ytick.color": MUTED,
    "axes.spines.top": False, "axes.spines.right": False,
})


@dataclass
class Domain:
    acc: str
    desc: str
    start: int
    end: int
    source: str
    ipr: str
    ipr_name: str
    colour: str = ""

    @property
    def group(self):
        return self.ipr or self.acc

    @property
    def is_pfam(self):
        return self.source.upper() == "PFAM"


@dataclass
class Chain:
    id: str
    protein: str
    offset: int
    length: int

    @property
    def start(self):
        return self.offset + 1

    @property
    def end(self):
        return self.offset + self.length


def read_interproscan(paths):
    """{sequence MD5: (protein ID, domains, coiled coils, disordered regions)} from InterProScan TSVs."""
    rows, descriptions, ipr_of, ipr_names = {}, {}, {}, {}
    for path in paths:
        for line in open(path):
            f = line.rstrip("\r\n").split("\t")
            if len(f) < 9:
                continue
            if len(f) > 12 and f[11].startswith("IPR"):
                ipr_of.setdefault(f[4], f[11])
                ipr_names.setdefault(f[11], f[12])
            if f[5] != "-":
                descriptions.setdefault(f[4], f[5])
            predicted = f[9:10] == ["InterPro-N"]  # score is a probability, not an e-value
            rows.setdefault(f[1].lower(), (f[0], []))[1].append((f[3], f[4], int(f[6]), int(f[7]), f[8], predicted))

    annotations = {}
    for md5, (protein, hits) in rows.items():
        scored = [h for h in hits if h[0].upper() in TIER]
        evalue = [h for h in scored if not h[5]]
        tier = lambda h: TIER[h[0].upper()]
        candidates = sorted((h for h in evalue if float(h[4]) <= MAX_EVALUE),
                            key=lambda h: (tier(h), float(h[4])) if tier(h) < 2 else (tier(h), h[3] - h[2], float(h[4])))
        # InterPro-N predictions then fill gaps, unless an e-value row for the same accession overlaps them
        candidates += sorted((h for h in scored if h[5] and not any(
            e[1] == h[1] and e[2] <= h[3] and h[2] <= e[3] for e in evalue)), key=lambda h: -float(h[4]))
        chosen = []
        for db, acc, start, end, *_ in candidates:
            if all(small_overlap(start, end, d.start, d.end) for d in chosen):
                ipr = ipr_of.get(acc)
                desc = descriptions.get(acc) or ipr_names.get(ipr) or acc
                chosen.append(Domain(acc, desc, start, end, db, ipr, ipr_names.get(ipr)))
        coils = sorted((s, e) for db, _, s, e, *_ in hits if db == "COILS")
        disorder = merge_spans((s, e) for db, _, s, e, *_ in hits if db == "MobiDB-lite")
        annotations[md5] = (protein, sorted(chosen, key=lambda d: d.start), coils, disorder)
    return annotations


def small_overlap(s1, e1, s2, e2):
    overlap = min(e1, e2) - max(s1, s2) + 1
    return overlap <= 0 or (overlap <= MAX_OVERLAP_AA and overlap <= MAX_OVERLAP_FRAC * min(e1 - s1 + 1, e2 - s2 + 1))


def merge_spans(spans):
    """Merge overlapping (start, end) spans, e.g. MobiDB-lite's nested predictions."""
    merged = []
    for start, end in sorted(spans):
        if merged and start <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return merged


def read_model(json_path):
    """PAE matrix and protein chains [(chain, sequence, C-alpha pLDDT, PAE token indices)] of an AF
    Server model. Atom names come from the CIF; pLDDT values from the JSON, which lists atoms in the
    same order. Ligands, ions and nucleic acids (no C-alpha) are skipped."""
    data = json.load(open(json_path))
    cols, residues, n_atoms = [], {}, 0
    for line in open(json_path.replace("_full_data_", "_model_").replace(".json", ".cif")):
        if line.startswith("_atom_site."):
            cols.append(line.split(".")[1].strip())
        elif line.startswith(("ATOM", "HETATM")):
            v = dict(zip(cols, line.split()))
            n_atoms += 1
            if v["label_seq_id"] != ".":
                res = residues.setdefault(v["label_asym_id"], {}).setdefault(
                    int(v["label_seq_id"]), [v["label_comp_id"], None])
                if v["label_atom_id"] == "CA":
                    res[1] = data["atom_plddts"][n_atoms - 1]
    assert n_atoms == len(data["atom_plddts"]), "CIF and JSON atom counts differ"

    first_token = {}  # modified residues get one token per atom, the first is the residue
    for i, key in enumerate(zip(data["token_chain_ids"], data["token_res_ids"])):
        first_token.setdefault(key, i)
    chains = []
    for chain, res in residues.items():
        if all(ca is not None for _, ca in res.values()):
            ids = sorted(res)
            chains.append((chain, "".join(AA.get(res[i][0], "X") for i in ids),
                           [res[i][1] for i in ids], [first_token[chain, i] for i in ids]))
    return np.asarray(data["pae"]), chains

def assign_colours(domains):
    """One colour per domain group, unique within the figure and generally also between figures as colour
    matching is hashed. """
    colours = {}
    for d in domains:
        if d.group not in colours:
            start = zlib.crc32(d.group.encode()) % len(PALETTE)
            order = PALETTE[start:] + PALETTE[:start]
            colours[d.group] = next((c for c in order if c not in colours.values()), order[0])
        d.colour = colours[d.group]


def pill(ax, start, end, y, height, **style):
    """Rounded box spanning residues start..end, with round corners in screen space."""
    (px0, py0), (px1, py1) = ax.transData.transform([(0, 0), (1, 1)])
    aspect = abs((px1 - px0) / (py1 - py0))
    radius = min(height / aspect / 2, (end - start + 1) / 2)
    ax.add_patch(patches.FancyBboxPatch((start - 0.5, y - height / 2), end - start + 1, height,
                                boxstyle=f"round,pad=0,rounding_size={radius}", mutation_aspect=aspect, **style))


def chain_ticks(chains):
    """Tick positions and labels numbered from 1 within each chain."""
    longest = max(c.length for c in chains)
    ticks = ticker.MaxNLocator(nbins=7 if len(chains) == 1 else 5, integer=True, steps=[1, 2, 5, 10]).tick_values(1, longest)
    step = max(1, int(round(ticks[1] - ticks[0])))
    positions = [(c.offset + k, str(k)) for c in chains for k in range(step, c.length + 1, step)]
    return [p for p, _ in positions], [l for _, l in positions]


def chain_title(c):
    return f"Chain {c.id}" + (f" · {c.protein}" if c.protein else "")


def domain_legend(fig, domains, y, coils=(), disorder=(), multi=False):
    groups = {}
    for d in domains:
        groups.setdefault(d.group, {}).setdefault(d.acc, d)
    handles = []
    for members in groups.values():
        d = next(iter(members.values()))
        if len(members) == 1:
            text = f"{d.desc} ({d.acc}" + ("" if d.is_pfam else f", {d.source}") + ")"
        else:  # several databases' hits for one InterPro entry
            accs = ", ".join(a + ("" if m.is_pfam else f" {m.source}") for a, m in members.items())
            text = f"{d.ipr_name or d.desc} ({d.ipr}: {accs})"
        handles.append(patches.Patch(facecolor=d.colour, label=textwrap.fill(text, 60)))
    if coils:
        handles.append(patches.Patch(facecolor="white", edgecolor=COIL, hatch="////", label="Coiled coil (COILS)"))
    if disorder:
        handles.append(patches.Patch(facecolor=DISORDER, edgecolor="none", label="Disordered region (MobiDB-lite)"))
    if multi:
        handles.append(lines.Line2D([], [], color=BOUNDARY, lw=1.6, label="Chain boundary"))
    if handles:
        fig.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.5, y), ncol=2 if len(handles) <= 10 else 3,
                   frameon=False, fontsize=8.5, handlelength=1.4, columnspacing=2)


def save(fig, name):
    fig.savefig(os.path.join(OUT_DIR, f"{name}.png"), dpi=300, bbox_inches="tight")
    plt.close(fig)


def plot_pae(name, pae, domains, chains):
    n, multi = len(pae), len(chains) > 1
    fig_w, fig_h = 7.2, 7.8
    x0, y0, w = 0.16, 0.25, 0.62
    h = w * fig_w / fig_h 
    fig = plt.figure(figsize=(fig_w, fig_h))
    ax = fig.add_axes([x0, y0, w, h])
    top = fig.add_axes([x0, y0 + h + 0.008, w, 0.03], sharex=ax)
    left = fig.add_axes([x0 - 0.008 - 0.03 * fig_h / fig_w, y0, 0.03 * fig_h / fig_w, h], sharey=ax)
    im = ax.imshow(pae, cmap="Greens_r", vmin=0, vmax=31.75, extent=(0.5, n + 0.5, n + 0.5, 0.5),
                   interpolation="nearest", aspect="auto")
    cb = fig.colorbar(im, cax=fig.add_axes([x0 + w + 0.03, y0, 0.025, h]))
    cb.set_label("Expected position error (Å)")
    cb.outline.set_visible(False)
    for d in domains:
        lo, hi = d.start - 0.5, d.end + 0.5
        ax.add_patch(patches.Rectangle((lo, lo), hi - lo, hi - lo, fill=False, ec=d.colour,
                               lw=3 if n <= 800 else 2 if n <= 1600 else 1.2))
        for x in (lo, hi) if len(domains) <= 20 else ():
            ax.axvline(x, color="white", lw=0.5, alpha=0.7)
            ax.axhline(x, color="white", lw=0.5, alpha=0.7)
        top.axvspan(lo, hi, color=d.colour, lw=0)
        left.axhspan(lo, hi, color=d.colour, lw=0)
    for strip in (top, left):
        strip.set_facecolor("#f1f0ec")
        strip.tick_params(left=False, bottom=False, labelleft=False, labelbottom=False)
        for spine in strip.spines.values():
            spine.set_visible(False)

    if multi:
        for c in chains[1:]:
            for a in (ax, top):
                a.axvline(c.offset + 0.5, color=BOUNDARY, lw=1.6, zorder=5)
            for a in (ax, left):
                a.axhline(c.offset + 0.5, color=BOUNDARY, lw=1.6, zorder=5)
        for c in chains:
            ax.add_patch(patches.Rectangle((c.offset + 0.5, c.offset + 0.5), c.length, c.length, fill=False,
                                   ec=BOUNDARY, lw=2.4, zorder=6))
            space = w * fig_w * c.length / n  # inches available for the title
            text = next((t for t in (chain_title(c), f"Chain {c.id}") if len(t) * 0.08 < space), c.id)
            mid, style = c.offset + c.length / 2 + 0.5, dict(fontsize=8.5, fontweight="bold", color=BOUNDARY)
            top.text(mid, 1.25, text, transform=top.get_xaxis_transform(), ha="center", va="bottom", **style)
            left.text(0, mid, text, transform=transforms.offset_copy(left.get_yaxis_transform(), fig=fig, x=-3, units="points"),
                      rotation=90, ha="right", va="center", **style)

    ax.set_xlim(0.5, n + 0.5)
    ax.set_ylim(n + 0.5, 0.5)
    ticks = chain_ticks(chains)
    ax.set_xticks(*ticks)
    ax.set_yticks(*ticks)
    within = " (numbered within each chain)" if multi else ""
    ax.set_xlabel("Scored residue" + within)
    ax.set_ylabel("Aligned residue" + within)
    ax.yaxis.set_tick_params(pad=40 if multi else 24)
    domain_legend(fig, domains, y0 - 0.075, multi=multi)
    save(fig, f"{name}_pae")


def plot_plddt(name, plddt, domains, coils, disorder, chains):
    n, multi = len(plddt), len(chains) > 1
    x = np.arange(1, n + 1)
    fig, (ax, track) = plt.subplots(2, 1, figsize=(min(20, max(11, n / 45)), 5.6), sharex=True,
                                    gridspec_kw={"height_ratios": [3, 1.1], "hspace": 0.08})

    for d in domains:
        ax.axvspan(d.start - 0.5, d.end + 0.5, color=d.colour, alpha=0.07, lw=0)
    segments = np.stack([np.column_stack([x[:-1], plddt[:-1]]), np.column_stack([x[1:], plddt[1:]])], axis=1)
    colours = np.array([next(c for lo, c, _ in PLDDT_BANDS if (a + b) / 2 >= lo) for a, b in zip(plddt, plddt[1:])])
    keep = np.ones(n - 1, dtype=bool)
    keep[[c.end - 1 for c in chains[:-1]]] = False
    ax.add_collection(collections.LineCollection(segments[keep], colors=list(colours[keep]), linewidths=2, capstyle="round"))
    ax.set_ylim(0, 100)
    ax.set_yticks([0, 50, 70, 90, 100])
    ax.set_ylabel("pLDDT")
    ax.grid(axis="y", color=GRID, lw=0.8, ls="--")
    ax.set_axisbelow(True)
    ax.tick_params(bottom=False)
    ax.spines["bottom"].set_visible(False)
    ax.legend(handles=[patches.Patch(color=c, label=l) for _, c, l in PLDDT_BANDS], loc="lower left",
              bbox_to_anchor=(0, 1.0), ncol=4, frameon=False, fontsize=8.5, handlelength=1.2)

    track.set_xlim(0.5, n + 0.5)
    track.set_ylim(-1.45, 0.7)
    for c in chains:
        track.plot([c.start, c.end], [0, 0], color="#c9c8c2", lw=7, solid_capstyle="round", zorder=1)
        if multi:
            ax.text(c.start + 0.01 * n, 2, chain_title(c), ha="left", va="bottom", fontsize=8.5, fontweight="bold",
                    color=BOUNDARY, zorder=6, bbox=dict(fc="white", ec="none", alpha=0.85, pad=1.5))
    for c in chains[1:]:
        for a in (ax, track):
            a.axvline(c.offset + 0.5, color=BOUNDARY, lw=1.6, zorder=5)
    for d in domains:
        pill(track, d.start, d.end, 0, 0.9, fc=d.colour, ec="white", lw=1.5, zorder=3)
    for start, end in coils:
        pill(track, start, end, -0.8, 0.24, fc="white", ec=COIL, hatch="////", lw=0.8, zorder=2)
    for start, end in disorder:
        pill(track, start, end, -1.2, 0.24, fc=DISORDER, ec="none", zorder=2)
    track.set_yticks([])
    track.spines["left"].set_visible(False)
    track.set_xticks(*chain_ticks(chains))
    track.set_xlabel(f"Residue, numbered within each chain ({len(chains)} chains, {n} aa in total)" if multi
                     else f"Residue (length {n} aa)")

    fig.canvas.draw()
    domain_legend(fig, domains, track.get_position().y0 - 0.12, coils, disorder, multi)
    save(fig, f"{name}_plddt")


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--json-dir", required=True, help="folder of unzipped AlphaFold Server downloads")
    p.add_argument("--tsv", required=True, nargs="+", help="InterProScan TSV files, or folders of them")
    args = p.parse_args()
    tsvs = [f for t in args.tsv for f in (sorted(glob.glob(os.path.join(t, "*.tsv"))) if os.path.isdir(t) else [t])]
    annotations = read_interproscan(tsvs)
    os.makedirs(OUT_DIR, exist_ok=True)

    flagged, plotted = [], set()
    for path in sorted(glob.glob(os.path.join(args.json_dir, "**", "fold_*_full_data_0.json"), recursive=True)):
        job = os.path.basename(path)[len("fold_"):-len("_full_data_0.json")]
        try:
            pae, chains = read_model(path)
            parts, domains, coils, disorder, plddt, tokens = [], [], [], [], [], []
            for chain, seq, chain_plddt, chain_tokens in chains:
                offset = len(plddt)
                protein, doms, cc, dis = annotations.get(hashlib.md5(seq.encode()).hexdigest(), (None, [], [], []))
                if protein is None:
                    flagged.append(f"{job} chain {chain}: sequence not in the InterProScan TSVs; plotted without domains")
                domains += [replace(d, start=d.start + offset, end=d.end + offset) for d in doms]
                coils += [(s + offset, e + offset) for s, e in cc]
                disorder += [(s + offset, e + offset) for s, e in dis]
                parts.append(Chain(chain, protein, offset, len(seq)))
                plddt += chain_plddt
                tokens += chain_tokens
            name = re.sub(r"[^\w.-]+", "_", parts[0].protein if len(parts) == 1 and parts[0].protein else job)
            assign_colours(domains)
            plot_pae(name, pae[np.ix_(tokens, tokens)], domains, parts)
            plot_plddt(name, np.array(plddt), domains, coils, disorder, parts)
        except Exception as e:
            plt.close("all")
            flagged.append(f"{job}: {type(e).__name__}: {e}")
            continue
        plotted.update(c.protein for c in parts)
        print(f"{name}: " + ", ".join(f"chain {c.id} = {c.protein or 'unmatched'}" for c in parts))

    flagged += [f"{p}: in the InterProScan TSVs but in no model" for p, *_ in annotations.values() if p not in plotted]
    for msg in flagged:
        print(f"  ! {msg}")


if __name__ == "__main__":
    main()