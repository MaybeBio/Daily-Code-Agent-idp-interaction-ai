# First-passage times of a Rouse chain whose two ends feel the two-sphere pair
# potential -- the SAME potential, thresholds and phi_inf grid the 1D backward-FPE
# stage uses, so the two MFPTs are directly comparable.
#
# PARAM.JL CONTRACT (spec/jobs/YYYYMMDD/): every physical and numerical parameter
# comes from the `param.jl` sitting next to this file via `PARAMS`; nothing about
# the chain, the spheres or the potential is written down twice.  In particular
#
#   nbeads        = PARAMS.rouse.s + 1        (tracked beads 1 and 1 + s)
#   kuhnLength    = PARAMS.rouse.a
#   friction, kBT = PARAMS.rouse.friction, PARAMS.rouse.kBT
#   r_min         = PARAMS.surface.R          (hard wall: the spheres cannot overlap)
#   dt            = 0.01 * tau_bond,  tau_bond = friction / (3 kBT / a^2)
#   phi_inf       = the swept axis, taken from the stored FPT-solver records
#
# dt is FIXED at a hundredth of the bond relaxation time rather than being a free
# knob: tau_bond = friction/stiffness is the fastest time scale in the chain (it is
# `timeScale` in src/rouse.jl, so this is exactly dtDimless = 0.01), and everything
# slower -- the subchain Rouse time tau_bond*s^2/pi^2, the barrier crossing -- is
# then resolved by construction.
#
# WHAT IS COMPARED.  The FPT stage (fisher_rate_from_fpt_solver.jl) reduces the
# bead-to-bead distance x to a 1D Markov coordinate diffusing with D_eff = 2kBT/gamma
# in U_tot(x) = U_ads(x) - 2 log x + 3x^2/(2 s a^2), and solves
#   escape:  x = R -> x_div   (reflecting at R, absorbing at x_div)
#   return:  x_div -> x = R   (absorbing at R, reflecting far out)
# Here the chain is integrated in full 3D: ONLY U_ads acts between the two tracked
# beads (the radial Jacobian -2 log x and the entropic spring are generated by the
# chain itself), and the same two first-passage problems are read off the A/B
# sojourn machinery of src/rouse.jl with the SAME landmarks,
#   a = R + contact_tol  (contact),        b = x_div  (the solver's dividing surface).
# So an A-sojourn IS an escape time and a B-sojourn IS a return time, and the gap
# between the two columns of the printed table is exactly the error of the Markovian
# 1D reduction -- which the internal Rouse modes are expected to make large: the
# reduction assumes the chain is slaved to x, while tau_Rouse here is orders of
# magnitude longer than the reduced-model MFPTs.
#
# INPUTS (read at include time; see the note at the read itself):
#   PARAMS.sim.output_dir/PARAMS.sim.interp_file  -- x_grid + U_full_interp (U_ads)
#   PARAMS.sim.output_dir/PARAMS.sim.fisher_file  -- x_div + the solver MFPTs
#
# Run through spec/local/20261009/run_all.sh, which runs the two input stages and then
#   ./runJL sim/sweep.jl spec/local/20261009/rouse_mfpt_attractive.jl 3 <output_dir>/rouse
# for every s in PARAMS.rouse.s_values at once (ROUSE_S selects the s, RUN_MODE the
# production / smoke configuration -- see param.jl).

using Droplet
using Statistics
using Printf
using CubicSplines: CubicSpline
import JSON

include(joinpath(@__DIR__, "param.jl"))

# Lattice species (unused -- the Rouse chain is off-lattice).
slist = []
checkpoint_path = ""

# ── Run-length / storage knobs ───────────────────────────────────────────────
# Deliberately NOT in param.jl: no other stage consumes them, they buy statistics
# rather than physics, and t_max is the one number that has to be retuned for
# every time budget.  Cost: ~1.2 us/step at s = 10, ~7.7 us/step at s = 110
# (20260927), and :distance_only additionally holds 8 bytes/step of
# trajectory in RAM -- :sojourn_only keeps only the interval lists.
#
# SIZE IT AGAINST tau_rouse, NOT against the solver MFPTs.  The end-to-end distance
# decorrelates on the subchain Rouse time tau_bond*s^2/pi^2 (= 100 * s^2/pi^2 steps,
# ~4e5 steps at s = 200), which is far LONGER than the reduced-model MFPTs.  A run of
# a few tau_rouse therefore samples a couple of excursions, drops the (long) sojourn
# still open at the end, and reports a mean biased low -- one 1e6-step trial found no
# crossing at all because the chain happened to start far out and had not yet relaxed.
#
# EQUAL WALL CLOCK ACROSS s.  The run length is t_max minutes per target! call, not a
# step count: the cost per step grows with the bead count (2 min at s = 10 vs 13 min
# at s = 110 for 1e8 steps, 20260927), so a fixed nsteps leaves the small-s CPUs idle
# while s = 310 finishes.  target! times a probe of its own chain and sizes nsteps to
# fill t_max (see "Size the run" below).
t_max       = SMOKE ? 2.0 : 720.0  # minutes of wall clock per target! call
save_mode   = :sojourn_only        # :sojourn_only | :distance_only
sample_skip = 100                  # subsampling of a stored distance trace
n_phi_run   = 14                    # phi_inf values to run, spread over the stored sweep
seed0       = 202610131

# ── Inputs ───────────────────────────────────────────────────────────────────
# Read HERE, at include time, i.e. BEFORE sim/sweep.jl stamps its CLI outdir into
# PARAMS.sim.output_dir: the potentials come from the directory param.jl names,
# while this sweep's own output goes to the outdir on the command line.
interp_path = joinpath(PARAMS.sim.output_dir, PARAMS.sim.interp_file)
fisher_path = joinpath(PARAMS.sim.output_dir, PARAMS.sim.fisher_file)
isfile(interp_path) || error("missing $interp_path -- run bvp_potential_interp.jl first")
isfile(fisher_path) || error("missing $fisher_path -- run fisher_rate_from_fpt_solver.jl first")
_ip = JSON.parsefile(interp_path)
_fp = JSON.parsefile(fisher_path)

_f(x)    = x === nothing ? NaN : Float64(x)              # JSON null -> NaN
_farr(v) = Float64[_f(x) for x in v]

# The PAIR potential only (U_ads), on the interp stage's x-grid.  U_tot's other two
# terms are the chain's own entropy and must not be added by hand here.
const X_GRID   = _farr(_ip["x_grid"])
const PHI_ALL  = _farr(_ip["phi_inf"])
const U_ADS    = [_farr(r) for r in (PARAMS.fpt.potential == :bvp ?
                                     _ip["U_full_interp"] : _ip["U_linear"])]

# The solver's sweep-wide dividing surface and its per-phi MFPTs: the landmarks the
# chain has to reproduce.  per_phi covers phi_infs[1:end-2] (the Fisher stencil
# drops the last two), so the swept axis is taken from the records themselves.
const X_DIV      = _f(_fp["x_div"])
const REC_PHI    = [_f(r["phi_inf"])     for r in _fp["per_phi"]]
const REC_ESC    = [_f(r["escape_mfpt"]) for r in _fp["per_phi"]]
const REC_RET    = [_f(r["return_mfpt"]) for r in _fp["per_phi"]]
const REC_RIDGE  = [_f(r["x_ridge"])     for r in _fp["per_phi"]]
const REC_BARR   = [_f(r["barrier"])     for r in _fp["per_phi"]]

# ── Chain constants derived from PARAMS ──────────────────────────────────────
const KBT      = PARAMS.rouse.kBT
const FRICTION = PARAMS.rouse.friction
const KUHN     = PARAMS.rouse.a
const BEADSEP  = Int(PARAMS.rouse.s)              # bonds between the tracked beads
const NBEADS   = BEADSEP + 1
const STIFF    = 3 * KBT / KUHN^2                 # kappa, as in _set_scaling_params!
const TAU_BOND = FRICTION / STIFF                 # bond relaxation time
const DT       = 0.01 * TAU_BOND / 16                  # => dtDimless = 0.01
const TAU_ROUSE = TAU_BOND * BEADSEP^2 / π^2      # subchain relaxation time
const R        = PARAMS.surface.R

# Contact threshold.  The tracked pair reflects off r_min = R and so never attains
# x = R exactly, while the solver starts its escape from a delta AT R; the discrete
# stand-in is the first node above the wall on the solver's escape grid
# range(R, x_div, Ngrid).
const CONTACT_TOL = (X_DIV - R) / (PARAMS.fpt.Ngrid - 1)
const A_BOUND     = R + CONTACT_TOL
const B_UNBOUND   = X_DIV

# ── Sweep axes ───────────────────────────────────────────────────────────────
# alphas = phi_inf, thinned to n_phi_run values spread evenly over the stored
# records: the well deepens monotonically with phi_inf, so the ends bracket a
# shallow and a deep attractive well.  beta = omega_b, carried for the record (the
# potentials were solved at PARAMS.sweep.omega_b_values).
# const PHI_SEL = unique(round.(Int, range(1, length(REC_PHI); length = n_phi_run)))
alphas  = REC_PHI[[3,5]]
betas   = PARAMS.sweep.omega_b_values
nparams = length(alphas)

# sim/sweep.jl runs keya = 1 : ncpus * div(nparams, ncpus), so a remainder is
# silently dropped -- and with ncpus > nparams NOTHING runs and every CPU writes an
# empty {}.  nparams is capped by the number of stored solver records, which is
# PARAMS.sweep.n_phi - 2 (the Fisher stencil drops the last two), NOT by n_phi_run.
# ncpus is stamped into PARAMS.sim only after this file is included, so read ARGS.
if length(ARGS) >= 3
    let nc = parse(Int, ARGS[3])
        nparams % nc == 0 || @warn """ncpus does not divide nparams: sim/sweep.jl \
            will drop alphas[$(nc * div(nparams, nc) + 1):$nparams]$(nc > nparams ? " -- i.e. run nothing at all" : "").  \
            Use ncpus in $(filter(n -> nparams % n == 0, 1:nparams)).""" nparams ncpus=nc
    end
end

blurb = "Rouse chain in the two-sphere pair potential: the escape (contact -> " *
        "dividing surface) and return (dividing surface -> contact) first-passage " *
        "times measured from the A/B sojourns of the full 3D chain, against the " *
        "same two MFPTs from the 1D backward-FPE reduction in fisher_rate_from_" *
        "fpt_solver.jl.  Same potential, same landmarks, same phi_inf: the ratio " *
        "is the error of the Markovian reduction of the end-to-end coordinate."

function target!(res, args...)
    slist, keya, alpha, beta, blurb = args
    t0 = time()

    # This alpha's row in the stored sweep (alphas came from REC_PHI, so both
    # lookups are exact matches, not nearest neighbours).
    krec = argmin(abs.(REC_PHI .- alpha))
    kphi = argmin(abs.(PHI_ALL .- alpha))
    @assert isapprox(REC_PHI[krec], alpha; rtol = 1e-9) "no solver record at phi_inf=$alpha"
    @assert isapprox(PHI_ALL[kphi], alpha; rtol = 1e-9) "no U_ads row at phi_inf=$alpha"

    p = Droplet.with(PARAMS.surface; phi_inf = alpha, omega_b = beta)

    # Pair potential U_ads(x) as a smooth function of the bead-to-bead distance:
    # a cubic spline through the tabulated row, continued with the terminal slope
    # below the wall (never sampled once the pair has reflected) and flat above the
    # last node, where the potential is already ~0.
    Urow   = U_ADS[kphi]
    slopel = (Urow[2] - Urow[1]) / (X_GRID[2] - X_GRID[1])
    uspl   = CubicSpline(X_GRID, Urow, extrapl = [slopel,], extrapr = [0,])
    adsorption_potential(x) = uspl[x]

    # f(x) = -dU_ads/dx by central difference off that single definition, so the
    # force the chain feels can never drift from the potential that is reported.
    h_fd = 1e-6
    attractive_force = x ->
        -(adsorption_potential(x + h_fd) - adsorption_potential(x - h_fd)) / (2 * h_fd)

    # The reduced 1D potential, for diagnostics only: this is what the FPT stage
    # integrates, and the last two terms are what the chain here generates itself.
    total_potential(x) = adsorption_potential(x) - 2 * log(x) +
                         3 * x^2 / (2 * BEADSEP * KUHN^2)

    # Distinct streams for every (s, alpha).
    seed = seed0 + 1000 * BEADSEP + keya
    chain(n) = RousePolymer(;
        boltzmannConst  = 1.0,
        temperature     = KBT,
        friction        = FRICTION,
        kuhnLength      = KUHN,
        r_min           = R,
        nbeads          = Int32(NBEADS),
        nsteps          = n,
        dt              = DT,
        trackedBead1    = 1,
        trackedBead2    = NBEADS,
        attractiveForce = attractive_force,
        saveMode        = save_mode,
        a               = A_BOUND,
        b               = B_UNBOUND,
        seed            = seed,
    )

    # ── Size the run to the wall-clock budget ──
    # Time a probe of this exact chain (same N, force, bounds) after a short warm-up
    # so compilation is not billed, growing it until it lasts 1% of t_max (>= 2 s;
    # a short probe taken while the other runs are still starting up misjudged the
    # speed by up to 25% in the smoke test), then spend what is left of t_max
    # (counted from t0, so the probe is included) on the run.
    probe = chain(1_000); init!(probe); simulate!(probe)
    n_probe, t_probe = 100_000, 0.0
    while true
        probe.nsteps = n_probe
        t_probe = @elapsed simulate!(probe)
        t_probe >= max(2, 0.6 * t_max) && break
        n_probe = ceil(Int, n_probe * 1.5 * max(2, 0.6 * t_max) / max(t_probe, 1e-3))
    end
    sec_per_step = t_probe / n_probe
    nsteps = max(floor(Int, (60 * t_max - (time() - t0)) / sec_per_step), 2)

    r = chain(nsteps)
    init!(r)
    simulate!(r)

    # The first interval of each region is dropped: whichever region the chain
    # starts in has its clock pinned to step 0 rather than to a threshold crossing.
    esc_times = Float64.(length(r.A_intervals) > 1 ? r.A_intervals[2:end] : Int[]) .* DT
    ret_times = Float64.(length(r.B_intervals) > 1 ? r.B_intervals[2:end] : Int[]) .* DT
    _mean(v)   = isempty(v) ? NaN : mean(v)
    _median(v) = isempty(v) ? NaN : median(v)

    res["blurb"]          = blurb
    res["alpha"]          = alpha
    res["beta"]           = beta
    res["keya"]           = keya
    res["s"]              = PARAMS.rouse.s
    res["run_mode"]       = RUN_MODE
    res["params"]         = to_dict(PARAMS)          # full parameter set, for provenance
    res["surface_params"] = Dict("nb" => p.nb, "chi_b" => p.chi_b, "kappa" => p.kappa,
                                 "omega_b" => p.omega_b, "R" => p.R, "L" => p.L,
                                 "phi_inf" => p.phi_inf)
    res["rouse_params"]   = Dict("nbeads" => NBEADS, "bead_separation" => BEADSEP,
                                 "kuhn_length" => KUHN, "kBT" => KBT,
                                 "friction" => FRICTION, "stiffness" => STIFF,
                                 "D_bead" => KBT / FRICTION, "D_eff" => D_eff(PARAMS.rouse),
                                 "dt" => DT, "nsteps" => nsteps,
                                 "t_max_min" => t_max, "sec_per_step" => sec_per_step,
                                 "seed" => seed,
                                 "tau_bond" => TAU_BOND, "tau_rouse" => TAU_ROUSE,
                                 "t_total" => nsteps * DT)

    # Landmarks, shared with the FPT stage.
    res["x_contact"]   = A_BOUND
    res["contact_tol"] = CONTACT_TOL
    res["x_div"]       = B_UNBOUND
    res["x_ridge"]     = REC_RIDGE[krec]
    res["barrier"]     = REC_BARR[krec]
    res["well_depth"]  = adsorption_potential(R)

    # Raw sojourns (in integration steps) and the first-passage samples in seconds.
    res["A_intervals"]  = r.A_intervals
    res["B_intervals"]  = r.B_intervals
    res["escape_times"] = esc_times
    res["return_times"] = ret_times

    # The comparison.  n_* and t_in_* say how far the means can be trusted: a
    # sojourn still running when the trajectory ends is discarded, so with few
    # completed intervals the sample mean is biased low.
    res["mfpt"] = Dict(
        "rouse_escape"    => _mean(esc_times),   "rouse_return"    => _mean(ret_times),
        "rouse_escape_median" => _median(esc_times),
        "rouse_return_median" => _median(ret_times),
        "solver_escape"   => REC_ESC[krec],      "solver_return"   => REC_RET[krec],
        "ratio_escape"    => _mean(esc_times) / REC_ESC[krec],
        "ratio_return"    => _mean(ret_times) / REC_RET[krec])
    res["n_escape"]  = length(esc_times)
    res["n_return"]  = length(ret_times)
    res["t_in_well"] = sum(r.A_intervals; init = 0) * DT
    res["t_in_bulk"] = sum(r.B_intervals; init = 0) * DT

    # Landscape, subsampled off the stored grid.
    res["pot_grid"]        = X_GRID[1:4:end]
    res["ads_potential"]   = adsorption_potential.(X_GRID[1:4:end])
    res["total_potential"] = total_potential.(X_GRID[1:4:end])

    res["distance_traj"]    = r.distanceTraj === nothing ? Float64[] :
                              r.distanceTraj[1:sample_skip:end]
    res["sample_skip"]      = sample_skip
    res["trace_dt"]         = DT * sample_skip
    res["bead_relax_time"]  = r.timeScale
    res["bead_relax_scale"] = r.posScale
    res["runtime_min"]      = (time() - t0) / 60.0

    return res
end
