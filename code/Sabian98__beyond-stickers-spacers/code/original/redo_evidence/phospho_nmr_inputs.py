"""
phospho_nmr_inputs.py — inputs for phospho_nmr_plan.md (hash 1851cf7c). Builds the unmodified and phosphorylated
constructs from the BMRB entity sequences (external_data/bmrb_phospho/raw, hashed), checks every site, and writes one
FASTA per protein (temperature in the file name, as submit_calvados.sh expects), the residues file and a README with the
pH and ionic strength of each submission, into the CALVADOS IDP folder input_nmr/ and a snapshot in gaivi/phospho_nmr/.

  ~/.venvs/finches/bin/python -I phospho_nmr_inputs.py
"""
import csv
import json
import os
import shutil

DYN = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(DYN, 'external_data', 'bmrb_phospho', 'raw')
CAL = '/Users/taseef/Downloads/Scripts/CALVADOS IDP'
OUT_CAL = os.path.join(CAL, 'input_nmr')
OUT_SNAP = os.path.join(DYN, 'gaivi', 'phospho_nmr')
RESIDUES = os.path.join(CAL, 'input_phospho', 'residues_phospho.csv')
N_REP = 3

# name, unmodified entry, phosphorylated entry, sites (construct numbering), T (K), pH, ionic strength (M)
PAIRS = [('PAGE4', 26544, 26545, [51], 273, 7.0, 0.100),
         ('p53TAD', 50510, 50511, [55], 298, 7.0, 0.170),
         ('Sic1', 16657, 16659, [7, 35, 47, 71, 78, 82], 278, 7.0, 0.200),
         ('NHE1tail', 26755, 27812, [15, 45, 48, 93, 101, 107], 273, 7.2, 0.150),
         ('HMGA1a', 27883, 27884, [99, 102, 103], 298, 7.0, 0.150),
         ('H1-0CTD', 27537, 27538, [22, 44, 56], 298, 5.5, 0.020)]


def entity_seq(bmrb_id):
    d = json.load(open(os.path.join(RAW, f'entry_{bmrb_id}_meta.json')))
    ent = d[str(bmrb_id)]['entity'][0]                     # the first entity is the construct (later ones: labelled variants)
    tags = dict((t[0], t[1]) for t in ent['tags'])
    return tags['Polymer_seq_one_letter_code'].replace('\n', '').replace(' ', '').strip()


def main():
    os.makedirs(OUT_CAL, exist_ok=True)
    os.makedirs(OUT_SNAP, exist_ok=True)
    rows, readme = [], []
    for name, unmod, phos, sites, T, ph, ionic in PAIRS:
        wt, ph_seq = entity_seq(unmod), entity_seq(phos)
        assert len(wt) == len(ph_seq), name
        assert set(wt) <= set('ACDEFGHIKLMNPQRSTVWY'), (name, set(wt) - set('ACDEFGHIKLMNPQRSTVWY'))
        xs = [k + 1 for k, c in enumerate(ph_seq) if c == 'X']
        assert xs == sites, (name, xs, sites)                       # the phosphorylated entry marks exactly these sites
        assert all(a == b for k, (a, b) in enumerate(zip(wt, ph_seq)) if k + 1 not in sites), name
        assert all(wt[s - 1] in 'ST' for s in sites), (name, [wt[s - 1] for s in sites])
        p = list(wt)
        for s in sites:
            p[s - 1] = 'B' if wt[s - 1] == 'S' else 'J'
        p = ''.join(p)
        fa = f'nmr_{name}_{T}K.fasta'
        with open(os.path.join(OUT_CAL, fa), 'w') as fh:
            for form, seq in (('WT', wt), ('P', p)):
                for r in range(1, N_REP + 1):
                    fh.write(f'>NMR-{name}-{form}-r{r}|{name}\n')
                    for k in range(0, len(seq), 60):
                        fh.write(seq[k:k + 60] + '\n')
        rows.append({'protein': name, 'bmrb_unmod': unmod, 'bmrb_phos': phos, 'N': len(wt),
                     'sites': ' '.join(f'{wt[s - 1]}{s}' for s in sites), 'T_K': T, 'pH': ph, 'ionic_M': ionic,
                     'fasta': fa, 'wt_seq': wt, 'phos_seq': p})
        readme.append(f'bash submit_calvados.sh input_nmr/{fa} --ph {ph} --ionic {ionic} '
                      f'--outroot /data/taseefr/phospho_nmr --residues input_nmr/residues_phospho.csv')
    shutil.copy(RESIDUES, os.path.join(OUT_CAL, 'residues_phospho.csv'))
    with open(os.path.join(OUT_SNAP, 'pairs.csv'), 'w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    txt = ['# NMR case-series runs (CALVADOS-2)', '',
           'Inputs for `BENDER-DYN/redo_evidence/phospho_nmr_plan.md` (hash 1851cf7c). Six proteins with NMR shifts of the',
           'unmodified and the phosphorylated construct in BMRB; each FASTA holds the unmodified construct (`-WT-`) and the',
           'phosphorylated one (`-P-`, B = pSer, J = pThr), three replicates each (36 runs). Every protein is simulated at the',
           'temperature, pH and ionic strength of its NMR sample, so each FASTA is submitted on its own with its own options.',
           'Generated by `BENDER-DYN/redo_evidence/phospho_nmr_inputs.py`; regenerate there rather than editing by hand.', '',
           '## Submit on GAIVI (one line per protein; always pass `--residues`)', '', '```bash',
           'source ~/calvados_env/bin/activate', 'cd "<CALVADOS IDP dir>"'] + readme + ['```', '',
           '| protein | BMRB unmod / phospho | N | sites | T (K) | pH | I (M) |', '|---|---|---|---|---|---|---|'] + \
          [f"| {r['protein']} | {r['bmrb_unmod']} / {r['bmrb_phos']} | {r['N']} | {r['sites']} | {r['T_K']} | {r['pH']} | "
           f"{r['ionic_M']} |" for r in rows] + \
          ['', 'Without `--residues`, prepare.py maps B to Asp and J to Leu and the runs are not phosphorylated. Copy',
           '`/data/taseefr/phospho_nmr/<T>K/NMR-*` (dcd + top.pdb) back to `BENDER-DYN/phospho_nmr/` when done.']
    open(os.path.join(OUT_CAL, 'README.md'), 'w').write('\n'.join(txt) + '\n')
    snap = os.path.join(OUT_SNAP, 'CALVADOS_IDP_snapshot', 'input_nmr')
    os.makedirs(snap, exist_ok=True)
    for f in os.listdir(OUT_CAL):
        if not f.startswith('.'):
            shutil.copy(os.path.join(OUT_CAL, f), snap)
    for r in rows:
        print(f"{r['protein']:9s} N {r['N']:3d}  {r['sites']:32s} {r['T_K']} K pH {r['pH']} I {r['ionic_M']}  -> {r['fasta']}")


if __name__ == '__main__':
    main()
