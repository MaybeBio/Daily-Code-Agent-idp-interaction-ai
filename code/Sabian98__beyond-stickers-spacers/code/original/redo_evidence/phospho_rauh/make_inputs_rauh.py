"""
make_inputs_rauh.py — CALVADOS-2 inputs for direct runs of the phosphorylated constructs with the published
phosphoresidue model (Rauh et al., Biophys. J. 2026), for the four NMR pairs that the reweighting check
(phospho_rauh.py) left with low ESS or a changed result: Sic1, H1-0 CTD, NHE1 tail, Tir. Three replicates of the
phosphorylated form only (12 runs); the unmodified runs are the existing ones (the published model changes only
the phosphoresidues).

Residues: residues_phospho_ptyr.csv (the simulated runs) with the B, J, Z rows replaced by the published values,
  B pSer  lambda 0.0925  sigma 0.601  MW 165.04  pKa 6.01   (CALVADOS package residues_pCALVADOS2.csv)
  J pThr  lambda 0.0013  sigma 0.635  MW 179.07  pKa 6.30   (same)
  Z pTyr  lambda 0.977461144934  sigma 0.703  MW 241.14  pKa 5.83   (study repository residue_files/residues.csv)
  q = -1 - 1 / (1 + 10^(pKa - pH)) at the sample pH, as in the package's single_pIDR/prepare.py,
so each pair gets its own residues file. Sequences are the P records of the existing FASTA files, renamed RAUH-*.
  python3 make_inputs_rauh.py   ->   CALVADOS IDP/input_rauh/{rauh_<pair>_<T>K.fasta, residues_rauh_<pair>.csv, README.md}
"""
import os

CAL = os.path.expanduser('~/Downloads/Scripts/CALVADOS IDP')
OUT = os.path.join(CAL, 'input_rauh')
BASE = os.path.join(CAL, 'input_nmr2', 'residues_phospho_ptyr.csv')
PUB = {'B': ('SEP', 165.04, 0.0925, 0.601, 6.01), 'J': ('TPO', 179.07, 0.0013, 0.635, 6.30),
       'Z': ('PTR', 241.14, 0.977461144934, 0.703, 5.83)}
# pair, source FASTA, T (K), pH, ionic strength (M)
PAIRS = [('Sic1', 'input_nmr/nmr_Sic1_278K.fasta', 278, 7.0, 0.2),
         ('H1-0CTD', 'input_nmr/nmr_H1-0CTD_298K.fasta', 298, 5.5, 0.02),
         ('NHE1tail', 'input_nmr/nmr_NHE1tail_273K.fasta', 273, 7.2, 0.15),
         ('Tir', 'input_nmr2/nmr2_Tir_283K.fasta', 283, 6.65, 0.15)]


def charge(pka, ph):
    return -1.0 - 1.0 / (1.0 + 10.0 ** (pka - ph))


def records(path):
    out, name, seq = [], None, []
    for line in open(path):
        line = line.strip()
        if line.startswith('>'):
            if name:
                out.append((name, ''.join(seq)))
            name, seq = line[1:], []
        elif line:
            seq.append(line)
    out.append((name, ''.join(seq)))
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    base = [l for l in open(BASE).read().splitlines() if l]
    assert base[0] == 'one,three,MW,lambdas,sigmas,q,bondlength'
    cmds, table = [], []
    for name, src, T, ph, ionic in PAIRS:
        rows = [l for l in base if l.split(',')[0] not in PUB]
        for one, (three, mw, lam, sig, pka) in PUB.items():
            rows.append(f'{one},{three},{mw},{lam},{sig},{charge(pka, ph):.6f},0.38')
        res = f'residues_rauh_{name}.csv'
        open(os.path.join(OUT, res), 'w').write('\n'.join(rows) + '\n')
        P = [(h, s) for h, s in records(os.path.join(CAL, src)) if '-P-' in h.split('|')[0]]
        assert len(P) == 3 and len({s for _, s in P}) == 1, name
        seq = P[0][1]
        assert set(seq) & set(PUB), name
        fa = f'rauh_{name}_{T}K.fasta'
        txt = ''
        for r in (1, 2, 3):
            txt += f'>RAUH-{name}-P-r{r}|{name}\n' + '\n'.join(seq[k:k + 60] for k in range(0, len(seq), 60)) + '\n'
        open(os.path.join(OUT, fa), 'w').write(txt)
        cmds.append(f'bash submit_calvados.sh input_rauh/{fa} --ph {ph} --ionic {ionic} '
                    f'--outroot /data/taseefr/phospho_rauh --residues input_rauh/{res}')
        qs = ', '.join(f'{k} {charge(PUB[k][4], ph):.2f}' for k in PUB if k in seq)
        table.append(f'| {name} | {len(seq)} | {T} | {ph} | {ionic} | {qs} |')
    readme = ['# NMR pairs with the published phosphoresidue model (CALVADOS-2)', '',
              'Robustness check of the NMR case series (exploratory, 2026-10-27). Phosphorylated constructs only, three',
              'replicates each (12 runs), with the published pSer/pThr model of Rauh et al. (Biophys. J. 2026) and the pTyr',
              'values of the study repository. Each pair has its own residues file, since the charge depends on the pH.',
              'Generated by `BENDER-DYN/redo_evidence/phospho_rauh/make_inputs_rauh.py`; regenerate there rather than',
              'editing by hand. Always pass `--residues`.', '', '```bash', 'source ~/calvados_env/bin/activate',
              'cd "<CALVADOS IDP dir>"'] + cmds + ['```', '',
              '| pair | N | T (K) | pH | I (M) | site charge |', '|---|---|---|---|---|---|'] + table + ['',
              'Copy `/data/taseefr/phospho_rauh/<T>K/RAUH-*` (dcd + top.pdb) back to `BENDER-DYN/phospho_rauh/<T>K/`.']
    open(os.path.join(OUT, 'README.md'), 'w').write('\n'.join(readme) + '\n')
    print('\n'.join(readme))


if __name__ == '__main__':
    main()
